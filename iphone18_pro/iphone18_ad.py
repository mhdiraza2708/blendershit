def plateau_height(x, y):
    """Height (mm) of the camera plateau above the back plate at plan position x, y."""
    top = B + 40.0
    ymin = B - PLAT_FLAT_BOTTOM
    sd_flat = box_sdf(x, y, 0.0, (ymin + top) / 2, PLAT_FLAT_HALF_W, (top - ymin) / 2, PLAT_FLAT_R)
    sd_side = (B - PLAT_SIDE_FROM_TOP) - y          # the full-width band at the top
    sd = smin(sd_flat, sd_side, 2.5)
    t = np.clip(1.0 - sd / PLAT_SLOPE, 0.0, 1.0)
    return PLAT_H * t * t * (3 - 2 * t)


