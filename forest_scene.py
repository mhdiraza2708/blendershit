def instancer_group(name, collection, viewport_fraction=1.0):
    ng = bpy.data.node_groups.new(name, "GeometryNodeTree")
    ng.interface.new_socket("Geometry", in_out="INPUT", socket_type="NodeSocketGeometry")
    ng.interface.new_socket("Geometry", in_out="OUTPUT", socket_type="NodeSocketGeometry")
    N, L = ng.nodes, ng.links
    gi, go = N.new("NodeGroupInput"), N.new("NodeGroupOutput")
    ci = N.new("GeometryNodeCollectionInfo")
    ci.transform_space = "ORIGINAL"
    ci.inputs["Collection"].default_value = collection
    ci.inputs["Separate Children"].default_value = True
    ci.inputs["Reset Children"].default_value = True

    def named(attr, dtype):
        n = N.new("GeometryNodeInputNamedAttribute")
        n.data_type = dtype
        n.inputs["Name"].default_value = attr
        return n.outputs["Attribute"]

    iop = N.new("GeometryNodeInstanceOnPoints")
    iop.inputs["Pick Instance"].default_value = True
    e2r = N.new("FunctionNodeEulerToRotation")
    L.new(gi.outputs[0], iop.inputs["Points"])
    L.new(ci.outputs[0], iop.inputs["Instance"])
    L.new(named("var", "INT"), iop.inputs["Instance Index"])
    L.new(named("rot", "FLOAT_VECTOR"), e2r.inputs[0])
    L.new(e2r.outputs[0], iop.inputs["Rotation"])
    L.new(named("scl", "FLOAT_VECTOR"), iop.inputs["Scale"])
    if viewport_fraction < 1.0:
        # show only a fraction of the instances in the viewport; renders get all of them
        isv = N.new("GeometryNodeIsViewport")
        rnd = N.new("FunctionNodeRandomValue")
        rnd.data_type = "BOOLEAN"
        rnd.inputs["Probability"].default_value = viewport_fraction
        notv = N.new("FunctionNodeBooleanMath")
        notv.operation = "NOT"
        orr = N.new("FunctionNodeBooleanMath")
        orr.operation = "OR"
        L.new(isv.outputs[0], notv.inputs[0])
        L.new(notv.outputs[0], orr.inputs[0])
        L.new(NB.sock(rnd.outputs, "Value"), orr.inputs[1])
        L.new(orr.outputs[0], iop.inputs["Selection"])
    L.new(iop.outputs[0], go.inputs[0])
    return ng


def scatter_object(name, P, rot, scl, var, coll, asset_coll, viewport_fraction=1.0):
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(P))
    me.vertices.foreach_set("co", np.ascontiguousarray(P, dtype=np.float32).ravel())
    set_attribute(me, "rot", rot, "POINT", "FLOAT_VECTOR")
    set_attribute(me, "scl", scl, "POINT", "FLOAT_VECTOR")
    set_attribute(me, "var", var, "POINT", "INT")
    me.update()
    ob = new_object(name, me, coll)
    mod = ob.modifiers.new("Scatter", "NODES")
    mod.node_group = instancer_group(name + "_Instancer", asset_coll, viewport_fraction)
    log(f"scatter {name}: {len(P):,} instances")
    return ob


class View:
    """Camera frustum in numpy form, used to only scatter what can be seen."""

    def __init__(self, pos, rot, tan_h, aspect):
        R = np.array(rot)
        self.pos = np.array(pos, dtype=np.float64)
        self.fwd = R @ np.array([0.0, 0.0, -1.0])
        self.right = R @ np.array([1.0, 0.0, 0.0])
        self.up = R @ np.array([0.0, 1.0, 0.0])
        self.tan_h = tan_h
        self.tan_v = tan_h * aspect
        self.heading = math.atan2(self.fwd[0], self.fwd[1])

    @classmethod
    def from_camera(cls, cam_ob, res):
        tan_h = (cam_ob.data.sensor_width / 2.0) / cam_ob.data.lens
        return cls(cam_ob.location, cam_ob.rotation_euler.to_matrix(), tan_h, res[1] / res[0])

    def visible(self, P, margin=0.12, pad=0.5):
        d = P - self.pos
        z = d @ self.fwd
        x = d @ self.right
        y = d @ self.up
        return ((z > 0.05) & (np.abs(x) < z * (self.tan_h + margin) + pad)
                & (np.abs(y) < z * (self.tan_v + margin) + pad))

    def wedge(self, rng, n, r0, r1, extra_angle=0.2):
        half = math.atan(self.tan_h) + extra_angle
        r = np.sqrt(rng.uniform(r0 * r0, r1 * r1, n))
        a = self.heading + rng.uniform(-half, half, n)
        return self.pos[0] + r * np.sin(a), self.pos[1] + r * np.cos(a), r

    def wedge_area(self, r0, r1, extra_angle=0.2):
        half = math.atan(self.tan_h) + extra_angle
        return half * (r1 * r1 - r0 * r0)

    def off_axis(self, x, y):
        """Horizontal angle between the view axis and the direction to (x, y)."""
        return np.abs(np.angle(np.exp(1j * (np.arctan2(x - self.pos[0], y - self.pos[1]) - self.heading))))

    def in_wedge(self, x, y, r0, r1, extra_angle=0.2):
        r = np.hypot(x - self.pos[0], y - self.pos[1])
        return (r >= r0) & (r <= r1) & (self.off_axis(x, y) <= math.atan(self.tan_h) + extra_angle)


class ViewSet:
    """The union of the camera's views: one for a still, several poses sampled along
    the camera move for an animation. Scattering covers everything any pose sees."""

    def __init__(self, views):
        self.views = views
        self.first = views[0]

    def sample(self, rng, density, r0, r1, extra_angle=0.2, count=None):
        """Uniform candidate points over the union of the views' ground wedges.
        Returns x, y and r = distance to the nearest camera position."""
        xs, ys = [], []
        area0 = self.first.wedge_area(r0, r1, extra_angle)
        for i, v in enumerate(self.views):
            if count is not None:
                n = int(count * v.wedge_area(r0, r1, extra_angle) / area0) if i else count
            else:
                # candidate count uses the default wedge angle, as the original still did,
                # so the still's layout stays exactly reproducible
                n = int(v.wedge_area(r0, r1) * density)
            x, y, r = v.wedge(rng, n, r0, r1, extra_angle)
            if len(self.views) == 1:
                return x, y, r
            keep = np.ones(len(x), dtype=bool)
            for u in self.views[:i]:                       # each region sampled once
                keep &= ~u.in_wedge(x, y, r0, r1, extra_angle)
            xs.append(x[keep])
            ys.append(y[keep])
        x, y = np.concatenate(xs), np.concatenate(ys)
        return x, y, self.distance(x, y)

    def distance(self, x, y):
        return np.min([np.hypot(x - v.pos[0], y - v.pos[1]) for v in self.views], axis=0)

    def in_cone(self, x, y, extra_angle):
        return np.any([v.in_wedge(x, y, 0.0, 1e9, extra_angle) for v in self.views], axis=0)


def poisson_disk(rng, x0, x1, y0, y1, r, k=24):
    """Bridson Poisson-disk sampling in a rectangle."""
    cell = r / math.sqrt(2)
    gw, gh = int((x1 - x0) / cell) + 1, int((y1 - y0) / cell) + 1
    grid = -np.ones((gw, gh), dtype=np.int64)
    pts, active = [], []

    def put(p):
        pts.append(p)
        active.append(len(pts) - 1)
        grid[int((p[0] - x0) / cell), int((p[1] - y0) / cell)] = len(pts) - 1

    put((rng.uniform(x0, x1), rng.uniform(y0, y1)))
    while active:
        i = active[rng.randrange(len(active))]
        px, py = pts[i]
        for _ in range(k):
            a = rng.uniform(0, 2 * math.pi)
            rr = rng.uniform(r, 2 * r)
            qx, qy = px + rr * math.cos(a), py + rr * math.sin(a)
            if not (x0 <= qx < x1 and y0 <= qy < y1):
                continue
            gx, gy = int((qx - x0) / cell), int((qy - y0) / cell)
            ok = True
            for ix in range(max(gx - 2, 0), min(gx + 3, gw)):
                for iy in range(max(gy - 2, 0), min(gy + 3, gh)):
                    j = grid[ix, iy]
                    if j >= 0 and (pts[j][0] - qx) ** 2 + (pts[j][1] - qy) ** 2 < r * r:
                        ok = False
                        break
                if not ok:
                    break
            if ok:
                put((qx, qy))
                break
        else:
            active.remove(i)
    return np.array(pts)


class Obstacles:
    """Circles (x, y, radius) that scattered things should keep away from."""

    def __init__(self):
        self.c = np.zeros((0, 3))

    def add(self, x, y, r):
        self.c = np.vstack([self.c, np.stack(np.broadcast_arrays(x, y, r), axis=-1).reshape(-1, 3)])

    def clearance(self, x, y):
        if len(self.c) == 0:
            return np.full(np.shape(x), 1e9)
        out = np.full(np.shape(x), 1e9)
        for i in range(0, len(self.c), 256):
            c = self.c[i:i + 256]
            d = np.sqrt((x[:, None] - c[None, :, 0]) ** 2 + (y[:, None] - c[None, :, 1]) ** 2) - c[None, :, 2]
            out = np.minimum(out, d.min(axis=1))
        return out


