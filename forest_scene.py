def sun_vector(azimuth_deg, elevation_deg, view_heading):
    a = view_heading + math.radians(azimuth_deg)
    e = math.radians(elevation_deg)
    return Vector((math.sin(a) * math.cos(e), math.cos(a) * math.cos(e), math.sin(e)))


def setup_world(scene, to_sun, strength):
    world = bpy.data.worlds.new("Forest_Sky")
    scene.world = world
    if not BLENDER_5:
        world.use_nodes = True
    nt = world.node_tree
    nt.nodes.clear()
    nb = NB(nt)
    sky = nb.node("ShaderNodeTexSky")
    for t in ("MULTIPLE_SCATTERING", "NISHITA"):
        try:
            sky.sky_type = t
            break
        except TypeError:
            continue
    sky.sun_disc = False
    sky.sun_elevation = math.asin(to_sun.z)
    # Blender's sky: rotation 0 puts the sun on +Y, 90 degrees on +X (measured empirically)
    sky.sun_rotation = math.atan2(to_sun.x, to_sun.y)
    sky.altitude = 300.0
    sky.air_density = 1.0
    for prop, val in (("aerosol_density", 2.5), ("dust_density", 2.5), ("ozone_density", 1.0)):
        if hasattr(sky, prop):
            setattr(sky, prop, val)
    bg = nb.node("ShaderNodeBackground", {"Color": sky, "Strength": strength})
    out = nb.node("ShaderNodeOutputWorld")
    nb.set(out, "Surface", bg)
    return world


