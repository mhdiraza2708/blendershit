def torus(name, R, r, coll, strength, seg=96, rseg=12):
    v, f = [], []
    for i in range(seg):
        a = 2 * math.pi * i / seg
        for j in range(rseg):
            b = 2 * math.pi * j / rseg
            v.append(((R + r * math.cos(b)) * math.cos(a), (R + r * math.cos(b)) * math.sin(a), r * math.sin(b)))
    for i in range(seg):
        for j in range(rseg):
            a0, a1 = i * rseg + j, ((i + 1) % seg) * rseg + j
            f.append((a0, a1, ((i + 1) % seg) * rseg + (j + 1) % rseg, i * rseg + (j + 1) % rseg))
    return emissive_mesh(name, v, f, coll, strength)


