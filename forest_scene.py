def _instance_offset(nb, co):
    """Shift a texture coordinate by the per-instance random value so that
    instanced copies of an asset do not share an identical pattern."""
    rnd = nb.node("ShaderNodeObjectInfo").outputs["Random"]
    off = nb.comb(nb.math("MULTIPLY", rnd, 91.7), nb.math("MULTIPLY", rnd, 37.3), nb.math("MULTIPLY", rnd, 53.9))
    return nb.vmath("ADD", co, off)


def _bark_growth(nb, co, col, height, obj_z, normal, shade_dir, algae_amount=0.5, moss_height=0.6):
    """Crustose lichen, green algae staining (shaded side, streaky) and moss on the root flare."""
    lich_n = nb.out(nb.noise(co, 2.6, 10, 0.68), "Fac")
    lich = nb.mapr(lich_n, 0.6, 0.625)
    col = nb.mix(nb.math("MULTIPLY", lich, 0.55), col, nb.mix(nb.out(nb.noise(co, 20.0, 4), "Fac"), "#8c8e7c", "#a3a591"))
    dots = nb.math("MULTIPLY", nb.mapr(nb.out(nb.voronoi(co, 55.0), "Distance"), 0.16, 0.08), lich)
    col = nb.mix(nb.math("MULTIPLY", dots, 0.6), col, "#2a2925")
    side = nb.mapr(nb.vmath("DOT_PRODUCT", normal, shade_dir), -0.3, 0.9)
    streak = nb.out(nb.noise(nb.vmath("MULTIPLY", co, (3.0, 3.0, 0.35)), 1.6, 6, 0.6), "Fac")
    patch = nb.mapr(nb.out(nb.noise(co, 0.9, 6, 0.6), "Fac"), 0.42, 0.6)
    low = nb.mapr(obj_z, 6.0, 0.2)
    algae = nb.math("MULTIPLY", nb.math("ADD", nb.math("MULTIPLY", side, nb.math("MULTIPLY", patch,
                                                                               nb.mapr(streak, 0.35, 0.65))),
                                        nb.math("MULTIPLY", low, 0.25)), nb.mapr(obj_z, 14.0, 5.0), clamp=True)
    col = nb.mix(nb.math("MULTIPLY", algae, algae_amount), col, "#565d3c")
    moss_n = nb.out(nb.noise(co, 2.2, 8, 0.62), "Fac")
    moss = nb.math("MULTIPLY", nb.mapr(obj_z, nb.math("ADD", moss_height, nb.math("MULTIPLY", moss_n, 0.6)), 0.05),
                   nb.mapr(nb.math("ADD", moss_n, nb.math("MULTIPLY", side, 0.2)), 0.5, 0.62))
    moss_col = nb.mix(nb.out(nb.noise(co, 30.0, 4), "Fac"), "#2b3a14", "#4c5e24")
    col = nb.mix(moss, col, moss_col)
    height = nb.math("ADD", height, nb.math("MULTIPLY", lich, 0.2))
    height = nb.math("ADD", height, nb.math("MULTIPLY", moss, nb.math("ADD", 0.8, nb.math(
        "MULTIPLY", nb.out(nb.noise(co, 110.0, 3), "Fac"), 0.7))))
    rough = nb.math("ADD", 0.62, nb.math("MULTIPLY", nb.math("ADD", moss, algae), 0.3), clamp=True)
    return col, height, rough


def mat_bark_beech(shade_dir, name="Bark_Beech"):
    """Smooth silver-grey beech bark: patchy tones, 'elephant skin' wrinkles, lichen, algae."""
    m, nb = new_material(name)
    co = _instance_offset(nb, nb.out(nb.attr("bark_co"), "Vector"))
    obj_z = nb.sep(nb.node("ShaderNodeTexCoord").outputs["Object"]).outputs["Z"]
    normal = nb.node("ShaderNodeNewGeometry").outputs["Normal"]
    big = nb.out(nb.noise(co, 0.5, 6, 0.55), "Fac")
    col = nb.ramp(big, [(0.3, "#57524a"), (0.47, "#6f6a60"), (0.6, "#837d72"), (0.72, "#908a7f")])
    # patchy darker / lighter blotches with fairly defined edges
    blot = nb.out(nb.noise(co, 2.2, 10, 0.7), "Fac")
    col = nb.mix(nb.math("MULTIPLY", nb.mapr(blot, 0.56, 0.6), 0.6), col, "#4a463f")
    col = nb.mix(nb.math("MULTIPLY", nb.mapr(blot, 0.42, 0.38), 0.4), col, "#9b968a")
    mottle = nb.out(nb.noise(co, 9.0, 8, 0.65), "Fac")
    col = nb.mix(nb.mapr(mottle, 0.45, 0.7, 0.0, 0.35), col, "#4b473f")
    # fine horizontal wrinkles / lenticel lines
    z = nb.sep(co).outputs["Z"]
    wobble = nb.math("MULTIPLY", nb.out(nb.noise(co, 3.0, 3), "Fac"), 9.0)
    wobble = nb.math("ADD", wobble, nb.math("MULTIPLY", nb.out(nb.noise(co, 14.0, 2), "Fac"), 3.0))
    rings = nb.math("SINE", nb.math("ADD", nb.math("MULTIPLY", z, 65.0), wobble))
    rings = nb.math("MULTIPLY", nb.mapr(rings, 0.88, 1.0),
                    nb.mapr(nb.out(nb.noise(co, 1.3, 4), "Fac"), 0.56, 0.66))
    col = nb.mix(nb.math("MULTIPLY", rings, 0.25), col, "#46423b")
    height = nb.math("ADD", nb.math("MULTIPLY", mottle, 0.25), nb.math("MULTIPLY", rings, -0.2))
    height = nb.math("ADD", height, nb.math("MULTIPLY", nb.mapr(blot, 0.56, 0.6), 0.15))
    col, height, rough = _bark_growth(nb, co, col, height, obj_z, normal, shade_dir, 0.65)
    pores = nb.out(nb.noise(co, 160.0, 3, 0.6), "Fac")
    height = nb.math("ADD", height, nb.math("MULTIPLY", pores, 0.15))
    bsdf = nb.principled(base=col, rough=rough, spec=0.35, normal=nb.bump(height, 0.4, 0.006))
    nb.output(bsdf)
    return m


def _fissured_bark(nb, co, scale=1.0, stretch=0.15):
    """Furrowed bark: strongly stretched, warped voronoi plates separated by wide
    V-shaped fissures, with a finer second layer and small horizontal breaks.
    Returns (plates 0..1, height, tone)."""
    st = nb.vmath("MULTIPLY", co, (1.0, 1.0, stretch))
    warp = nb.out(nb.noise(nb.vmath("MULTIPLY", co, (1.0, 1.0, 0.35)), 2.0 * scale, 3, 0.5), "Color")
    st = nb.vmath("ADD", st, nb.vmath("SCALE", nb.vmath("SUBTRACT", warp, (0.5, 0.5, 0.5)), scale=0.09 / scale))
    e1 = nb.out(nb.voronoi(st, 13.0 * scale, "DISTANCE_TO_EDGE"), "Distance")
    e2 = nb.out(nb.voronoi(nb.vmath("ADD", st, (3.1, 7.7, 1.3)), 7.0 * scale, "DISTANCE_TO_EDGE"), "Distance")
    edge = nb.math("MINIMUM", e1, nb.math("MULTIPLY", e2, 1.8))
    plates = nb.mapr(edge, 0.0, 0.2, interp="SMOOTHSTEP")
    brk = nb.out(nb.voronoi(nb.vmath("MULTIPLY", co, (1.0, 1.0, 2.2)), 16.0 * scale, "DISTANCE_TO_EDGE"), "Distance")
    brk = nb.mapr(brk, 0.0, 0.05)
    tone = nb.out(nb.noise(co, 6.0 * scale, 8, 0.65), "Fac")
    height = nb.math("ADD", nb.math("MULTIPLY", plates, nb.math("ADD", 0.88, nb.math("MULTIPLY", brk, 0.12))),
                     nb.math("MULTIPLY", tone, 0.2))
    return plates, height, tone


def mat_bark_oak(shade_dir):
    m, nb = new_material("Bark_Oak")
    co = _instance_offset(nb, nb.out(nb.attr("bark_co"), "Vector"))
    obj_z = nb.sep(nb.node("ShaderNodeTexCoord").outputs["Object"]).outputs["Z"]
    normal = nb.node("ShaderNodeNewGeometry").outputs["Normal"]
    plates, height, tone = _fissured_bark(nb, co)
    plate_col = nb.ramp(tone, [(0.3, "#453a30"), (0.55, "#5d5145"), (0.8, "#716454")])
    plate_col = nb.mix(nb.math("MULTIPLY", nb.math("POWER", plates, 3.0), 0.3), plate_col, "#8a7d6c")
    col = nb.mix(plates, "#17110d", plate_col)
    col, height, rough = _bark_growth(nb, co, col, height, obj_z, normal, shade_dir, 0.4, 0.9)
    fine = nb.out(nb.noise(co, 120.0, 3, 0.6), "Fac")
    height = nb.math("ADD", height, nb.math("MULTIPLY", fine, 0.08))
    bsdf = nb.principled(base=col, rough=nb.math("ADD", rough, 0.12, clamp=True), spec=0.3,
                         normal=nb.bump(height, 0.9, 0.02))
    nb.output(bsdf)
    return m


