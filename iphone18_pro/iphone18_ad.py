def build_control_groups(rig):
    """Shared animated values. 'FinishScan' sweeps the four launch finishes over the
    phone (a glowing scan line at each front); 'ScreenCtl' wakes the display."""
    ng, nb, out = new_group("FinishScan", [("Alu", "NodeSocketColor"), ("Glass", "NodeSocketColor"),
                                            ("Glow", "NodeSocketFloat")])
    tc = nb.node("ShaderNodeTexCoord", object=rig)
    y = nb.out(nb.sep(tc.outputs["Object"]), "Y")
    s = nb.mapr(y, (-B - 4) * MM, (B + 4) * MM, 0.0, 1.0, clamp=False)
    scan = nb.node("ShaderNodeValue", name="Scan", label="Scan")
    scan.outputs[0].default_value = 0.0
    alu = FINISHES[FINISH_ORDER[0]][0]
    glass = FINISHES[FINISH_ORDER[0]][1]
    alu, glass = hexcol(alu), hexcol(glass)
    glow = 0.0
    for k in range(1, len(FINISH_ORDER)):
        front = nb.math("SUBTRACT", scan.outputs[0], float(k - 1))
        m = nb.mapr(nb.math("SUBTRACT", front, s), -0.012, 0.012)
        ca, cg = FINISHES[FINISH_ORDER[k]]
        alu = nb.mix(m, alu, ca)
        glass = nb.mix(m, glass, cg)
        band = nb.mapr(nb.math("ABSOLUTE", nb.math("SUBTRACT", s, front)), 0.0, 0.010, 1.0, 0.0)
        live = nb.math("MULTIPLY", nb.mapr(front, 0.0, 0.03), nb.mapr(front, 1.0, 0.97))
        g = nb.math("MULTIPLY", nb.math("POWER", band, 3.0), live)
        glow = g if isinstance(glow, float) else nb.math("ADD", glow, g)
    nb.links.new(nb.out(alu), out.inputs["Alu"])
    nb.links.new(nb.out(glass), out.inputs["Glass"])
    nb.links.new(nb.out(glow), out.inputs["Glow"])

    def value_group(name, keys):
        g, b, o = new_group(name, [(k, "NodeSocketFloat") for k in keys])
        for k in keys:
            v = b.node("ShaderNodeValue", name=k, label=k)
            v.outputs[0].default_value = 0.0
            b.links.new(v.outputs[0], o.inputs[k])
        return g
    sg = value_group("ScreenCtl", ["On", "Time"])
    cg = value_group("ChipCtl", ["Glow", "Heat", "Phase"])
    lg = value_group("LensCtl", ["SensorGlow"])
    return ng, sg, cg, lg


def mat_aluminium(fg, name, rough=0.26, antenna=False):
    m, nb = new_material(name)
    f = use_group(nb, fg)
    metal = nb.principled(base=f.outputs["Alu"], metal=1.0, rough=rough, spec=0.5)
    shader = metal
    if antenna:
        oc = nb.sep(nb.node("ShaderNodeTexCoord").outputs["Object"])
        x = nb.math("ABSOLUTE", nb.out(oc, "X"))
        y = nb.out(oc, "Y")
        side = nb.mapr(x, (A - 4.2) * MM, (A - 3.9) * MM)
        bands = 0.0
        for yc, w in ANTENNA_BANDS:
            d = nb.math("ABSOLUTE", nb.math("SUBTRACT", y, yc * MM))
            b = nb.mapr(d, w / 2 * MM, (w / 2 - 0.04) * MM)
            bands = b if isinstance(bands, float) else nb.math("MAXIMUM", bands, b)
        mask = nb.math("MULTIPLY", side, bands)
        plastic = nb.principled(base=nb.mix(0.5, f.outputs["Alu"], (0.0, 0.0, 0.0)), metal=1.0, rough=0.42, spec=0.3)
        mix = nb.node("ShaderNodeMixShader")
        nb.set(mix, 0, mask)
        nb.set(mix, 1, metal)
        nb.set(mix, 2, plastic)
        shader = mix
    em = nb.node("ShaderNodeEmission", {"Color": (1.0, 0.97, 0.94), "Strength": nb.math("MULTIPLY", f.outputs["Glow"], 5.0)})
    add = nb.node("ShaderNodeAddShader")
    nb.set(add, 0, shader)
    nb.set(add, 1, em)
    nb.output(add)
    return m


def logo_mask(res=1024):
    """Apple-logo silhouette (as seen from the back) as a signed-distance raster in a
    16.32 x 20.04 mm box with a 4% margin."""
    def circ(X, Y, cx, cy, r):
        return np.hypot(X - cx, Y - cy) - r
    rx0, rx1, ry0, ry1 = -8.357, 7.861, -9.987, 10.018      # raw outline extents
    sx, sy = (rx1 - rx0) / LOGO["w"], (ry1 - ry0) / LOGO["h"]
    rcx, rcy = (rx0 + rx1) / 2, (ry0 + ry1) / 2
    hw, hh = LOGO["w"] / 2 * 1.04, LOGO["h"] / 2 * 1.04
    nyp = int(res * hh / hw)
    xs = np.linspace(-hw, hw, res)
    ys = np.linspace(-hh, hh, nyp)
    X, Y = np.meshgrid(xs * sx + rcx, ys * sy + rcy)
    up = smin(circ(X, Y, -3.6, 1.6, 4.7), circ(X, Y, 3.6, 1.6, 4.7), 1.5)
    lo = smin(circ(X, Y, -2.85, -5.55, 4.45), circ(X, Y, 2.85, -5.55, 4.45), 2.4)
    d = smin(up, lo, 5.5)
    d = np.maximum(d, -circ(X, Y, 9.25, 0.55, 3.85))                 # the bite
    t0, t1 = np.array([0.3, 5.95]), np.array([4.3, 10.0])            # the leaf
    mid = (t0 + t1) / 2
    ax = (t1 - t0) / np.linalg.norm(t1 - t0)
    nrm = np.array([-ax[1], ax[0]])
    c, wl = np.linalg.norm(t1 - t0) / 2, 1.45
    R = (c * c + wl * wl) / (2 * wl)
    leaf = np.maximum(circ(X, Y, *(mid + nrm * (R - wl)), R), circ(X, Y, *(mid - nrm * (R - wl)), R))
    d = np.minimum(d, leaf)
    px = (xs[1] - xs[0]) * sx
    alpha = np.clip(0.5 - d / px, 0.0, 1.0).astype(np.float32)
    img = bpy.data.images.new("AppleLogoMask", res, nyp, alpha=False, float_buffer=False)
    img.colorspace_settings.name = "Non-Color"     # before the pixels: changing it regenerates the image
    rgba = np.ones((nyp, res, 4), np.float32)
    rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = alpha
    img.pixels.foreach_set(rgba.ravel())
    img.update()
    img.pack()
    return img, hw, hh


def mat_back_glass(fg):
    m, nb = new_material("BackGlass")
    f = use_group(nb, fg)
    img, hw, hh = logo_mask()
    oc = nb.sep(nb.node("ShaderNodeTexCoord").outputs["Object"])
    # back-view logo coordinates: mirrored X
    lx = nb.math("MULTIPLY", nb.math("SUBTRACT", nb.out(oc, "X"), LOGO["cx"] * MM), -1.0)
    ly = nb.math("SUBTRACT", nb.out(oc, "Y"), LOGO["cy"] * MM)
    u = nb.mapr(lx, -hw * MM, hw * MM, 0, 1, clamp=False)
    v = nb.mapr(ly, -hh * MM, hh * MM, 0, 1, clamp=False)
    tex = nb.node("ShaderNodeTexImage", image=img, extension="CLIP", interpolation="Cubic")
    nb.set(tex, "Vector", nb.comb(u, v, 0.0))
    logo = nb.out(tex, "Color")
    logo_f = nb.out(nb.sep(logo), "X")
    base = nb.mix(logo_f, f.outputs["Glass"], nb.mix(0.35, f.outputs["Alu"], (0.0, 0.0, 0.0)))
    rough = nb.mixf(logo_f, 0.55, 0.06)
    bsdf = nb.principled(base=base, rough=rough, spec=nb.mixf(logo_f, 0.22, 0.6), metal=nb.mixf(logo_f, 0.0, 0.85))
    em = nb.node("ShaderNodeEmission", {"Color": (1.0, 0.97, 0.94), "Strength": nb.math("MULTIPLY", f.outputs["Glow"], 5.0)})
    add = nb.node("ShaderNodeAddShader")
    nb.set(add, 0, bsdf)
    nb.set(add, 1, em)
    nb.output(add)
    return m


