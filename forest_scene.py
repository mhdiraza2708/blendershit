def pick_device(want_gpu):
    """'GPU' when asked for (or when a GPU is already enabled in the Preferences),
    otherwise 'CPU'."""
    try:
        prefs = bpy.context.preferences.addons["cycles"].preferences
    except (KeyError, AttributeError):
        return "CPU"
    if want_gpu:
        for backend in ("OPTIX", "CUDA", "HIP", "METAL", "ONEAPI"):
            try:
                prefs.compute_device_type = backend
            except TypeError:                  # backend not available in this build
                continue
            prefs.refresh_devices()
            gpus = [d for d in prefs.devices if d.type == backend]
            if gpus:
                for d in prefs.devices:
                    d.use = d.type == backend
                log(f"GPU rendering via {backend}: {', '.join(d.name for d in gpus)}")
                return "GPU"
        log("no usable GPU found - rendering on the CPU")
        return "CPU"
    if prefs.compute_device_type != "NONE" and any(d.use and d.type != "CPU" for d in prefs.devices):
        return "GPU"
    return "CPU"


def setup_render(scene, opts):
    scene.render.engine = "CYCLES"
    c = scene.cycles
    c.device = pick_device(getattr(opts, "gpu", False))
    c.samples = opts.samples
    c.use_adaptive_sampling = True
    c.adaptive_threshold = 0.03
    c.use_denoising = True
    try:
        c.denoiser = "OPENIMAGEDENOISE"
        c.denoising_input_passes = "RGB_ALBEDO_NORMAL"
        c.denoising_prefilter = "ACCURATE"
        c.denoising_quality = "HIGH"
    except (TypeError, AttributeError):
        pass
    # Bounce budget tuned for speed: the long paths cost a lot and add little here.
    c.max_bounces = 8
    c.diffuse_bounces = 3
    c.glossy_bounces = 2
    c.transmission_bounces = 4
    c.volume_bounces = 0            # single scattering in the haze is enough for the shafts
    c.transparent_max_bounces = 8
    if getattr(opts, "preset", "") == "video":      # hundreds of frames: trim the budget further
        c.max_bounces, c.diffuse_bounces, c.transmission_bounces = 6, 2, 3
    c.sample_clamp_direct = 0.0
    c.sample_clamp_indirect = 6.0
    c.blur_glossy = 1.0
    c.caustics_reflective = False
    c.caustics_refractive = False
    c.use_light_tree = True
    r = scene.render
    r.resolution_x, r.resolution_y = opts.res
    r.resolution_percentage = 100
    r.film_transparent = False
    r.filter_size = 1.2
    if opts.threads:
        r.threads_mode = "FIXED"
        r.threads = opts.threads
    r.image_settings.file_format = "PNG"
    r.image_settings.color_depth = "8"
    r.image_settings.compression = 15
    vs = scene.view_settings
    vs.view_transform = "AgX"
    try:
        vs.look = LOOK["look"]
    except TypeError:
        pass
    vs.exposure = LOOK["exposure"]


def _try_input(node, key, value):
    """Set an input socket when this Blender version has it (4.5+ turned many node
    properties into sockets). Returns False if the socket is missing or incompatible."""
    try:
        NB.sock(node.inputs, key).default_value = value
        return True
    except (KeyError, TypeError, ValueError):
        return False


def setup_compositor(scene):
    """Photographic finish: soft bloom on highlights, a touch of lateral chromatic
    aberration and a gentle vignette. Works with the Blender 5 node-group compositor,
    the socket-based 4.5 nodes and the property-based 4.2-4.4 nodes."""
    w, h = scene.render.resolution_x, scene.render.resolution_y
    if hasattr(scene, "compositing_node_group"):                       # Blender 5.x
        ng = bpy.data.node_groups.new("Forest Finish", "CompositorNodeTree")
        ng.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
        scene.compositing_node_group = ng
        N, L = ng.nodes, ng.links
        final_input = N.new("NodeGroupOutput").inputs[0]
    else:                                                              # Blender 4.x
        scene.use_nodes = True
        N, L = scene.node_tree.nodes, scene.node_tree.links
        N.clear()
        final_input = N.new("CompositorNodeComposite").inputs["Image"]
    rl = N.new("CompositorNodeRLayers")
    rl.scene = scene

    glare = N.new("CompositorNodeGlare")
    if not _try_input(glare, "Type", "Bloom"):
        try:
            glare.glare_type = "BLOOM"
        except TypeError:                   # Bloom arrived in 4.2; fall back to Fog Glow
            glare.glare_type = "FOG_GLOW"
    if not _try_input(glare, "Quality", "High"):
        glare.quality = "HIGH"
    if not _try_input(glare, "Highlights Threshold", 1.5):
        glare.threshold = 1.5
    if not _try_input(glare, "Strength", 0.22):
        glare.mix = -0.78
    if not _try_input(glare, "Size", 0.85):
        glare.size = 8

    lens = N.new("CompositorNodeLensdist")
    _try_input(lens, "Dispersion", 0.012)
    if not _try_input(lens, "Fit", True):
        lens.use_fit = True

    ell = N.new("CompositorNodeEllipseMask")
    if not _try_input(ell, "Size", (0.92, 0.92)):
        ell.mask_width, ell.mask_height = 0.92, 0.92
    blur = N.new("CompositorNodeBlur")
    if not _try_input(blur, "Size", (w * 0.25, h * 0.25)):
        blur.filter_type = "GAUSS"
        blur.size_x, blur.size_y = int(w * 0.25), int(h * 0.25)
    try:
        vig = N.new("CompositorNodeMixRGB")                            # 4.x
        vig.blend_type = "MULTIPLY"
        vig.inputs[0].default_value = 0.4
        vig_a, vig_b, vig_out = vig.inputs[1], vig.inputs[2], vig.outputs[0]
    except RuntimeError:
        vig = N.new("ShaderNodeMix")                                   # 5.x
        vig.data_type, vig.blend_type = "RGBA", "MULTIPLY"
        NB.sock(vig.inputs, "Factor_Float").default_value = 0.4
        vig_a, vig_b = NB.sock(vig.inputs, "A_Color"), NB.sock(vig.inputs, "B_Color")
        vig_out = NB.sock(vig.outputs, "Result_Color")

    L.new(rl.outputs["Image"], glare.inputs["Image"])
    L.new(NB.sock(glare.outputs, "Image"), lens.inputs["Image"])
    L.new(lens.outputs["Image"], vig_a)
    L.new(ell.outputs["Mask"], blur.inputs["Image"])
    L.new(blur.outputs["Image"], vig_b)
    L.new(vig_out, final_input)


