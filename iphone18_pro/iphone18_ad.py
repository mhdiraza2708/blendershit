PLAT_Z = -HT - PLAT_H                     # plateau top surface (z of the flat top)
IRIS_BLADES = 9
IRIS_PIVOT_R, IRIS_GAMMA, IRIS_K = 5.6, math.radians(20.0), -0.56
IRIS_OPEN_R = 4.4                          # aperture radius at f/1.48 (mm, in the model)
F_STOPS = [1.48, 1.8, 2.8, 4.0]           # the Fusion Main camera's four apertures


def iris_angle(fnum):
    """Blade rotation (radians) that gives the aperture for f-number `fnum`."""
    r = IRIS_OPEN_R * F_STOPS[0] / fnum
    return math.acos((r - IRIS_K) / IRIS_PIVOT_R) - IRIS_GAMMA


