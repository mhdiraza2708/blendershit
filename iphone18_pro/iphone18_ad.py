def lathe(name, prof, coll, seg=96, center=(0, 0, 0), axis=-1, closed=False, smooth=True,
          sharp_angle=40, mat=None):
    """Revolve a (r, h) polyline about an axis parallel to Z through `center` (mm).
    h is measured along `axis` (-1 = towards the back). Points with r == 0 become poles."""
    cx, cy, cz = center
    th = np.linspace(0, 2 * np.pi, seg, endpoint=False)
    verts, rows = [], []
    for r, h in prof:
        z = cz + axis * h
        if r < 1e-9:
            rows.append([len(verts)])
            verts.append((cx, cy, z))
        else:
            rows.append(list(range(len(verts), len(verts) + seg)))
            verts.extend(zip(cx + r * np.cos(th), cy + r * np.sin(th), np.full(seg, z)))
    faces, flat = [], []
    idx = list(range(len(prof)))
    pairs = list(zip(idx[:-1], idx[1:]))
    if closed:
        pairs.append((idx[-1], idx[0]))
    for ka, kb in pairs:
        ra, rb = rows[ka], rows[kb]
        if len(ra) == 1 and len(rb) == 1:
            continue
        planar = abs(prof[ka][1] - prof[kb][1]) < 1e-9
        n0 = len(faces)
        if len(ra) == 1:
            faces += [(ra[0], rb[i], rb[(i + 1) % seg]) for i in range(seg)]
        elif len(rb) == 1:
            faces += [(ra[i], ra[(i + 1) % seg], rb[0]) for i in range(seg)]
        else:
            faces += [(ra[i], ra[(i + 1) % seg], rb[(i + 1) % seg], rb[i]) for i in range(seg)]
        if planar:
            flat += range(n0, len(faces))
    ob = make_mesh(name, verts, faces, coll, smooth=smooth, sharp_angle=sharp_angle)
    fix_normals(ob)          # consistent outward normals: glass refraction depends on them
    for i in flat:           # flat discs and rings stay flat: smooth fans would act like lenses
        ob.data.polygons[i].use_smooth = False
    if mat is not None:
        ob.data.materials.append(mat)
    return ob


def slab(name, outline_fn, prof, coll, mat=None, sharp_angle=40, uv_fn=None):
    """Loft a closed outline through (d, z) profile rings, capping both ends with n-gons.
    outline_fn() -> (pts, normals)."""
    pts, nrm = outline_fn()
    N = len(pts)
    rings = [np.column_stack([pts - d * nrm, np.full(N, z)]) for d, z in prof]
    ii = np.arange(N)
    faces = [list(range(N))[::-1], list(range((len(rings) - 1) * N, len(rings) * N))]
    for k in range(len(rings) - 1):
        a0, a1 = k * N + ii, k * N + (ii + 1) % N
        faces.extend(np.stack([a0, a1, a1 + N, a0 + N], 1).tolist())
    verts = np.vstack(rings)
    ob = make_mesh(name, verts, faces, coll, sharp_angle=sharp_angle,
                   uvs=uv_fn(verts) if uv_fn else None)
    fix_normals(ob)
    ob.data.polygons[0].use_smooth = False      # the planar caps: flat, or the n-gon
    ob.data.polygons[1].use_smooth = False      # interpolates bent normals across its face
    if mat is not None:
        ob.data.materials.append(mat)
    return ob


def stadium(w, h, n_round=24):
    """Outline fn for a stadium/capsule w x h (centred)."""
    r = min(w, h) / 2
    return lambda: rounded_outline(w / 2, h / 2, r * 0.999, 2.0, n_round, n_round)


def disc_flat(name, r, coll, z, center=(0, 0), seg=64, mat=None, axis=1):
    th = np.linspace(0, 2 * np.pi, seg, endpoint=False)
    v = [(center[0], center[1], z)] + [(center[0] + r * math.cos(t), center[1] + r * math.sin(t), z) for t in th]
    f = [(0, 1 + i, 1 + (i + 1) % seg) if axis > 0 else (0, 1 + (i + 1) % seg, 1 + i) for i in range(seg)]
    ob = make_mesh(name, v, f, coll, smooth=False)
    if mat is not None:
        ob.data.materials.append(mat)
    return ob


def place(ob, loc=(0, 0, 0), rot=(0, 0, 0)):
    ob.location = Vector(loc) * MM
    ob.rotation_euler = rot
    return ob


