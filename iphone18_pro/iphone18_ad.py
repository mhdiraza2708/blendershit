def mat_sensor(lg):
    """Image sensor: iridescent micro-lens grid that glows violet as the iris opens."""
    m, nb = new_material("Sensor")
    ctl = use_group(nb, lg)
    oc = nb.sep(nb.node("ShaderNodeTexCoord").outputs["Object"])
    x, y = nb.out(oc, "X"), nb.out(oc, "Y")
    r = nb.math("MULTIPLY", nb.math("SQRT", nb.math("ADD", nb.math("MULTIPLY", x, x), nb.math("MULTIPLY", y, y))), 1000.0)
    k = 2 * math.pi * 1000.0 / 0.16                       # 0.16 mm micro-lens pitch
    grid = nb.math("MULTIPLY", nb.math("ABSOLUTE", nb.math("SINE", nb.math("MULTIPLY", x, k))),
                   nb.math("ABSOLUTE", nb.math("SINE", nb.math("MULTIPLY", y, k))))
    fall = nb.mapr(r, 0.0, 5.0, 1.0, 0.25)
    col = nb.mix(nb.mapr(r, 0.5, 4.5), (0.42, 0.20, 1.0), (0.10, 0.25, 1.0))
    amt = nb.math("MULTIPLY", nb.math("MULTIPLY", fall, nb.mapr(grid, 0.0, 1.0, 0.85, 1.0)), ctl.outputs["SensorGlow"])
    nb.output(nb.principled(base=(0.02, 0.02, 0.03), metal=1.0, rough=0.12, film=420.0, film_ior=1.6,
                            emit=col, emit_str=nb.math("MULTIPLY", amt, 1.3)))
    return m


def mat_screen(sg):
    """OLED panel: black when off; a slow liquid gradient wallpaper when on."""
    m, nb = new_material("Display")
    ctl = use_group(nb, sg)
    uv = nb.node("ShaderNodeTexCoord").outputs["UV"]
    tm = ctl.outputs["Time"]
    noise = nb.node("ShaderNodeTexNoise", noise_dimensions="4D")
    nb.set(noise, "Vector", uv)
    nb.set(noise, "W", tm)
    nb.set(noise, "Scale", 0.9)
    nb.set(noise, "Detail", 2.0)
    nb.set(noise, "Distortion", 0.6)
    wave = nb.node("ShaderNodeTexWave", wave_type="BANDS", bands_direction="DIAGONAL")
    nb.set(wave, "Vector", nb.vmath("ADD", uv, nb.vmath("SCALE", nb.out(noise, "Color"), scale=0.55)))
    nb.set(wave, "Scale", 0.55)
    nb.set(wave, "Distortion", 0.9)
    nb.set(wave, "Detail Scale", 0.6)
    nb.set(wave, "Phase Offset", nb.math("MULTIPLY", tm, 0.8))
    col = nb.ramp(nb.out(wave, "Fac"), [(0.0, "#050106"), (0.30, "#24040e"), (0.48, "#7a1030"),
                                        (0.56, "#e0485a"), (0.60, "#ffc2a8"), (0.65, "#b52a4a"),
                                        (0.78, "#3a0a24"), (0.90, "#1a1638"), (1.0, "#040309")])
    v = nb.out(nb.sep(uv), "Y")
    vign = nb.mapr(v, 1.0, 0.55, 0.45, 1.0)     # darker under the clock
    col = nb.mix(1.0, col, nb.comb(vign, vign, vign), blend="MULTIPLY")
    strength = nb.math("MULTIPLY", ctl.outputs["On"], 1.7)
    nb.output(nb.principled(base=(0.0, 0.0, 0.0), rough=0.08, spec=0.2, emit=col, emit_str=strength))
    return m


