class Branch:
    __slots__ = ("pts", "rad", "level", "kind", "cum", "length")

    def __init__(self, pts, rad, level, kind="branch"):
        self.pts = np.asarray(pts, dtype=np.float64)
        self.rad = np.asarray(rad, dtype=np.float64)
        self.level = level
        self.kind = kind
        self.cum = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(self.pts, axis=0), axis=1))])
        self.length = float(self.cum[-1])

    def sample(self, t):
        t = np.atleast_1d(np.asarray(t, dtype=np.float64))
        s = np.clip(t, 0.0, 1.0) * self.length
        i = np.clip(np.searchsorted(self.cum, s, side="right") - 1, 0, len(self.pts) - 2)
        seg = np.maximum(self.cum[i + 1] - self.cum[i], 1e-9)
        f = ((s - self.cum[i]) / seg)[:, None]
        p = self.pts[i] * (1.0 - f) + self.pts[i + 1] * f
        tan = nrm(self.pts[i + 1] - self.pts[i])
        r = self.rad[i] * (1.0 - f[:, 0]) + self.rad[i + 1] * f[:, 0]
        return p, tan, r


def grow(rng, start, direction, length, r0, r1, seg, wobble, tropism, level, kind="branch"):
    n = max(2, int(math.ceil(length / seg)))
    step = length / n
    d = Vector(direction).normalized()
    p = Vector(start)
    pts = [tuple(p)]
    w = wobble * math.sqrt(step)
    trop = Vector((0.0, 0.0, tropism * step))
    for _ in range(n):
        d = (d + Vector((rng.gauss(0, w), rng.gauss(0, w), rng.gauss(0, w))) + trop).normalized()
        p = p + d * step
        pts.append(tuple(p))
    t = np.linspace(0.0, 1.0, n + 1)
    return Branch(pts, r0 + (r1 - r0) * t ** 0.9, level, kind)


def child_direction(tan, az, ang):
    t = Vector(tan).normalized()
    ref = Vector((0.0, 0.0, 1.0)) if abs(t.z) < 0.95 else Vector((1.0, 0.0, 0.0))
    side = t.cross(ref).normalized()
    side = Matrix.Rotation(az, 3, t) @ side
    return (t * math.cos(ang) + side * math.sin(ang)).normalized()


