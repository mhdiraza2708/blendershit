def rounded_outline(a, b, cl, n, nx, ny, dense=2401):
    """Rounded rectangle (half extents a, b) with superellipse corners of blend
    length cl and exponent n (n=2 is a circular arc). Returns (pts, normals) of a
    closed CCW loop of 2*(nx+ny) points that starts at the bottom-left corner's
    diagonal: nx segments along the bottom arc, ny up the right, nx along the top,
    ny down the left. Points are evenly spaced along each arc."""
    m = dense if dense % 2 else dense + 1
    t = np.linspace(0.0, np.pi / 2, m)
    cu, cv = np.cos(t) ** (2.0 / n), np.sin(t) ** (2.0 / n)
    cu[-1], cv[0] = 0.0, 0.0
    cx, cy = a - cl, b - cl
    bl = np.stack([-cx - cl * cu, -cy - cl * cv], 1)
    br = np.stack([cx + cl * cu[::-1], -cy - cl * cv[::-1]], 1)
    tr = np.stack([cx + cl * cu, cy + cl * cv], 1)
    tl = np.stack([-cx - cl * cu[::-1], cy + cl * cv[::-1]], 1)
    mid = m // 2

    def line(p, q, k=400):
        s = np.linspace(0, 1, k)[1:-1, None]
        return p[None] * (1 - s) + q[None] * s

    parts = [bl[mid:], line(bl[-1], br[0]), br, line(br[-1], tr[0]), tr,
             line(tr[-1], tl[0]), tl, line(tl[-1], bl[0]), bl[:mid + 1]]
    marks, loop, count = [], [], 0
    for i, p in enumerate(parts):
        if i in (0, 2, 4, 6):
            marks.append(count + (0 if i == 0 else mid))
        loop.append(p)
        count += len(p)
    poly = np.concatenate(loop)
    seg = np.linalg.norm(np.diff(poly, axis=0), axis=1)
    keep = np.concatenate([[True], seg > 1e-12])
    remap = np.cumsum(keep) - 1
    marks = [int(remap[k]) for k in marks] + [int(remap[len(poly) - 1])]
    poly = poly[keep]
    s = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(poly, axis=0), axis=1))])
    tang = np.gradient(poly, axis=0)
    tang[0] = tang[-1] = poly[1] - poly[-2]
    tang /= np.linalg.norm(tang, axis=1, keepdims=True)
    pts, tns = [], []
    for k, cnt in enumerate((nx, ny, nx, ny)):
        sv = np.linspace(s[marks[k]], s[marks[k + 1]], cnt + 1)[:-1]
        pts.append(np.stack([np.interp(sv, s, poly[:, 0]), np.interp(sv, s, poly[:, 1])], 1))
        tns.append(np.stack([np.interp(sv, s, tang[:, 0]), np.interp(sv, s, tang[:, 1])], 1))
    pts, tns = np.concatenate(pts), np.concatenate(tns)
    tns /= np.linalg.norm(tns, axis=1, keepdims=True)
    nrm = np.stack([tns[:, 1], -tns[:, 0]], 1)
    return pts, nrm


def arc_counts(a, b, cl, n, spacing):
    """Segment counts (nx, ny) that give roughly `spacing` mm between points."""
    p, _ = rounded_outline(a, b, cl, n, 64, 64)
    per = np.linalg.norm(np.diff(np.vstack([p, p[:1]]), axis=0), axis=1)
    lx, ly = per[:64].sum(), per[64:128].sum()
    return max(4, int(round(lx / spacing))), max(4, int(round(ly / spacing)))


def coons_grid(ring, nx, ny):
    """Transfinite (Coons) interpolation of a closed loop laid out as by
    rounded_outline(). Returns (grid (nx+1, ny+1, 2), index map into ring for the
    boundary or -1)."""
    N = len(ring)
    i = np.arange(nx + 1)
    j = np.arange(ny + 1)
    cb = ring[i]                                   # bottom, left -> right
    cr = ring[nx + j]                              # right, bottom -> top
    ct = ring[nx + ny + (nx - i)]                  # top, left -> right
    cl = ring[(2 * nx + 2 * ny - j) % N]           # left, bottom -> top
    u = (i / nx)[:, None, None]
    v = (j / ny)[None, :, None]
    p00, p10, p01, p11 = ring[0], ring[nx], ring[2 * nx + ny], ring[nx + ny]
    g = ((1 - v) * cb[:, None] + v * ct[:, None] + (1 - u) * cl[None] + u * cr[None]
         - ((1 - u) * (1 - v) * p00 + u * (1 - v) * p10 + (1 - u) * v * p01 + u * v * p11))
    idx = -np.ones((nx + 1, ny + 1), dtype=np.int64)
    idx[:, 0] = i
    idx[nx, :] = nx + j
    idx[:, ny] = nx + ny + (nx - i)
    idx[0, :] = (2 * nx + 2 * ny - j) % N
    return g, idx


def quarter(n, k, inv=False):
    """Superellipse quarter from (1,0) to (0,1), k points: returns (cos-ish, sin-ish)."""
    t = np.linspace(0, np.pi / 2, k)
    c, s = np.cos(t) ** (2.0 / n), np.sin(t) ** (2.0 / n)
    c[-1], s[0] = 0.0, 0.0
    return (c[::-1], s[::-1]) if inv else (c, s)


