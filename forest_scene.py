def catmull_rom(points, samples=60):
    P = np.asarray(points, dtype=np.float64)
    P = np.vstack([2 * P[0] - P[1], P, 2 * P[-1] - P[-2]])
    t = np.linspace(0.0, 1.0, samples, endpoint=False)[:, None]
    out = []
    for i in range(1, len(P) - 2):
        p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
        out.append(0.5 * (2 * p1 + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t ** 2
                          + (-p0 + 3 * p1 - 3 * p2 + p3) * t ** 3))
    out.append(P[-2][None])
    return np.vstack(out)


class FootPath:
    def __init__(self, ctrl, half_width):
        rough = catmull_rom(ctrl, 80)
        seg = np.linalg.norm(np.diff(rough, axis=0), axis=1)
        s = np.concatenate([[0.0], np.cumsum(seg)])
        fine = np.arange(0.0, s[-1], 0.05)
        self.pts = np.stack([np.interp(fine, s, rough[:, 0]), np.interp(fine, s, rough[:, 1])], axis=1)
        self.kd = KDTree(len(self.pts))
        for i, (x, y) in enumerate(self.pts):
            self.kd.insert((x, y, 0.0), i)
        self.kd.balance()
        self.half_width = half_width

    def distance(self, x, y):
        x = np.asarray(x, dtype=np.float64).ravel()
        y = np.asarray(y, dtype=np.float64).ravel()
        find = self.kd.find
        return np.fromiter((find((a, b, 0.0))[2] for a, b in zip(x, y)), dtype=np.float64, count=len(x))

    def mask(self, d):
        """1 on the trodden path, 0 off it."""
        return smoothstep(self.half_width * 1.35, self.half_width * 0.55, d)


class Terrain:
    def __init__(self, seed, path):
        self.pn = Perlin(seed * 31 + 5)
        self.path = path

    def height(self, x, y, d=None):
        n = self.pn
        x = np.asarray(x, dtype=np.float64)
        y = np.asarray(y, dtype=np.float64)
        h = (2.2 * n.fbm(x / 85.0, y / 85.0, 3)
             + 0.55 * n.fbm(x / 21.0 + 13.1, y / 21.0 - 4.7, 3)
             + 0.07 * n.fbm(x / 3.5 - 7.3, y / 3.5 + 2.9, 2))
        h = h + 0.028 * y
        if d is None:
            d = self.path.distance(x, y).reshape(x.shape)
        return h - 0.07 * np.exp(-(d / 0.75) ** 2)

    def normal(self, x, y, eps=0.15):
        big = np.full(np.shape(x), 1e3)
        hx = (self.height(x + eps, y, big) - self.height(x - eps, y, big)) / (2 * eps)
        hy = (self.height(x, y + eps, big) - self.height(x, y - eps, big)) / (2 * eps)
        return nrm(np.stack([-hx, -hy, np.ones_like(hx)], axis=-1))


def _graded_axis(lo, hi, base, growth):
    """Grid coordinates that are dense around 0 and coarser further away."""
    pos, x = [0.0], 0.0
    while x < hi:
        x = min(hi, x + base + growth * abs(x))
        pos.append(x)
    neg, x = [], 0.0
    while x > lo:
        x = max(lo, x - base - growth * abs(x))
        neg.append(x)
    return np.array(neg[::-1] + pos)


def build_terrain(terrain, mat, coll, cam_xy):
    xs = _graded_axis(-300.0, 300.0, 0.12, 0.02) + cam_xy[0]
    ys = _graded_axis(-45.0, 390.0, 0.12, 0.012) + cam_xy[1]
    X, Y = np.meshgrid(xs, ys)
    d = terrain.path.distance(X, Y).reshape(X.shape)
    Z = terrain.height(X, Y, d)
    nx, ny = len(xs), len(ys)
    V = np.stack([X, Y, Z], axis=-1).reshape(-1, 3)
    i = np.arange(ny - 1)[:, None]
    j = np.arange(nx - 1)[None, :]
    a = i * nx + j
    quads = np.stack([a, a + 1, a + nx + 1, a + nx], axis=-1).reshape(-1, 4)
    mb = MeshBuilder()
    mb.add_verts(V, {"path_mask": ("FLOAT", terrain.path.mask(d).ravel())})
    uv = V[quads][..., :2] / 4.0
    mb.add_faces(quads, uv)
    me = mb.build("Terrain", [mat])
    log(f"terrain: {len(V):,} vertices")
    return new_object("Terrain", me, coll)


