def crown_shape(tc):
    return 0.25 + 0.75 * math.sin(math.pi * (0.2 + 0.8 * tc))


def generate_skeleton(sp, rng, scale=1.0):
    """Returns (branches, info). Units: metres, tree base at the origin."""
    H = rng.uniform(*sp["height"]) * scale
    R = rng.uniform(*sp["radius"]) * scale
    branches = []

    # --- trunk: dense rings near the flared base -------------------------------
    seg = max(0.08, min(0.4, H / 60.0))
    zs = np.concatenate([np.linspace(-0.6, 0.0, 3, endpoint=False),
                         np.linspace(0.0, min(1.8, 0.35 * H), 14, endpoint=False),
                         np.arange(min(1.8, 0.35 * H), H, seg), [H]])
    zc = np.maximum(zs, 0.0)
    lean = rng.gauss(0.0, sp["lean"])
    lean_az = rng.uniform(0, 2 * math.pi)
    sw = sp["sway"] * rng.uniform(0.4, 1.0)
    wl1, wl2 = rng.uniform(7.0, 14.0) * scale, rng.uniform(9.0, 18.0) * scale
    ph1, ph2 = rng.uniform(0, 2 * math.pi), rng.uniform(0, 2 * math.pi)
    fz = zc / H
    ox = lean * zc * math.cos(lean_az) + sw * (np.sin(2 * math.pi * zc / wl1 + ph1) - math.sin(ph1)) * fz
    oy = lean * zc * math.sin(lean_az) + sw * (np.sin(2 * math.pi * zc / wl2 + ph2) - math.sin(ph2)) * fz
    rad = np.maximum(R * np.maximum(1.0 - fz, 0.0) ** sp["taper"], 0.004 + 0.02 * scale)
    trunk = Branch(np.stack([ox, oy, zs], axis=1), rad, 0, "trunk")
    branches.append(trunk)
    t_of_z = lambda z: (z + 0.6) / (H + 0.6)   # noqa: E731  (trunk is close to straight)

    # --- surface roots -------------------------------------------------------
    nroots = rng.randint(*sp["roots"])
    root_az = sorted((i + rng.uniform(-0.3, 0.3)) * 2 * math.pi / max(nroots, 1) + rng.uniform(0, 0.5)
                     for i in range(nroots))
    for az in root_az:
        d = Vector((math.cos(az), math.sin(az), -rng.uniform(0.3, 0.45)))
        start = Vector((R * 0.3 * math.cos(az), R * 0.3 * math.sin(az), R * 0.45))
        L = rng.uniform(1.2, 2.2) * R / 0.3
        branches.append(grow(rng, start, d, L, R * 0.36, 0.02, 0.12, 0.3, -0.25, 1, "root"))

    # --- dead stubs on the clear bole ------------------------------------------
    cb = rng.uniform(*sp["crown_base"])
    for _ in range(rng.randint(*sp["stubs"])):
        z = rng.uniform(2.0, max(2.5, cb * H))
        p, tan, r = trunk.sample(t_of_z(z))
        d = child_direction(tan[0], rng.uniform(0, 2 * math.pi), math.radians(rng.uniform(55, 95)))
        L = rng.uniform(0.08, 0.6)
        r0 = min(r[0] * 0.8, rng.uniform(0.015, 0.05))
        branches.append(grow(rng, p[0], d, L, r0, r0 * 0.7, 0.1, 0.1, 0.0, 1, "stub"))

    # --- limbs, forks, branches, twigs -------------------------------------------
    levels = sp["levels"]

    def spawn(parent, lvl):
        if lvl >= len(levels):
            return
        P = levels[lvl]
        count = P["density"] * parent.length * (P["end"] - P["start"])
        n = int(count + rng.random())
        az0 = rng.uniform(-0.3, 0.3) if P["planar"] else rng.uniform(0, 2 * math.pi)
        for i in range(n):
            t = P["start"] + (P["end"] - P["start"]) * (i + rng.uniform(0.2, 0.8)) / max(n, 1)
            p, tan, r = parent.sample(t)
            az = az0 + i * math.radians(P["rotate"]) + rng.gauss(0.0, 0.25)
            d = child_direction(tan[0], az, math.radians(rng.uniform(*P["angle"])))
            L = parent.length * P["length"] * (1.0 - 0.6 * t) * rng.uniform(0.75, 1.15)
            if L < 0.05:
                continue
            r0 = min(r[0] * P["radius"], r[0] * 0.85)
            b = grow(rng, p[0], d, L, r0, max(0.0018, r0 * 0.2), P["seg"], P["wobble"], P["tropism"], lvl + 2)
            branches.append(b)
            spawn(b, lvl + 1)

    Lp = sp["limbs"]
    nl = rng.randint(*Lp["count"])
    az0 = rng.uniform(0, 2 * math.pi)
    limb_specs = []
    for i in range(nl):
        tc = (i + rng.uniform(0.15, 0.85)) / nl
        limb_specs.append((tc, az0 + i * math.radians(Lp["rotate"]) + rng.gauss(0.0, 0.3),
                           math.radians(lerp(Lp["angle"][0], Lp["angle"][1], tc) + rng.gauss(0.0, 6.0)),
                           H * rng.uniform(*Lp["length"]) * crown_shape(tc), Lp["radius"], False))
    for _ in range(rng.randint(*sp["forks"])):
        limb_specs.append((rng.uniform(0.0, 0.12), rng.uniform(0, 2 * math.pi), math.radians(rng.uniform(14, 26)),
                           (1.0 - cb) * H * rng.uniform(0.75, 0.95), 0.72, True))
    for tc, az, ang, L, rr, fork in limb_specs:
        z = (cb + (0.97 - cb) * tc) * H
        p, tan, r = trunk.sample(t_of_z(z))
        d = child_direction(tan[0], az, ang)
        r0 = min(r[0] * rr * (1.0 if fork else 0.6 + 0.4 * crown_shape(tc)), r[0] * 0.85)
        limb = grow(rng, p[0], d, L, r0, max(0.003, r0 * 0.12), Lp["seg"], Lp["wobble"] * (0.6 if fork else 1.0),
                    Lp["tropism"] * (1.5 if fork else 1.0), 1, "limb")
        branches.append(limb)
        spawn(limb, 0)
    info = dict(H=H, R=R, crown_base=cb * H, root_az=root_az)
    return branches, info


def trunk_radial(info, sp, rng):
    """Root flare with buttresses aligned to the surface roots + bark bumps."""
    amount, fh = sp["flare"], sp["flare_h"] * max(0.3, info["R"] / 0.3)
    lobes = [(a, rng.uniform(0.7, 1.0)) for a in info["root_az"]]
    wav = [(k, rng.uniform(0.008, 0.03) / (1 + 0.25 * k), rng.uniform(0, 2 * math.pi), rng.uniform(-0.8, 0.8))
           for k in range(2, 11)]

    def radial(th, P):
        z = np.maximum(P[:, 2], 0.0)[:, None]
        lob = np.zeros_like(th)
        for a, w in lobes:
            dth = np.angle(np.exp(1j * (th - a)))
            lob += w * np.exp(-(dth / 0.33) ** 2)
        lob = 0.18 + np.minimum(lob, 1.3)
        f = 1.0 + amount * np.exp(-z / fh) * lob[None, :]
        bumps = 1.0
        for k, amp, ph, c in wav:
            bumps = bumps + amp * np.sin(k * th[None, :] + ph + c * z)
        return f * bumps
    return radial


def tree_mesh(name, sp, seed, detail, bark_mat, leaf_mat, scale=1.0, leaf_detail=None):
    """Tree mesh (bark = material 0, leaves = material 1). `detail` sets the branch
    tessellation; `leaf_detail` (defaults to `detail`) the leaf outline: 2 = 12-triangle
    leaves for things seen up close, otherwise 8-triangle leaves."""
    rng = random.Random(seed)
    leaf_detail = detail if leaf_detail is None else leaf_detail
    branches, info = generate_skeleton(sp, rng, scale)
    mb = MeshBuilder()
    edge = 0.035 if detail < 2 else 0.022
    max_sides = 28 if detail < 2 else 40
    radial = trunk_radial(info, sp, rng)
    for k, b in enumerate(branches):
        r0 = float(b.rad[0])
        sides = max(3 if r0 < 0.006 else 4, min(max_sides, int(round(2 * math.pi * r0 / edge))))
        if b.kind == "trunk":
            sides = max(sides, 16)
            add_tube(mb, b.pts, b.rad, sides, 0, radial, cap=True)
        elif b.kind == "root":
            add_tube(mb, b.pts, b.rad, max(sides, 10), 0,
                     lambda th, P: np.broadcast_to(1.0 - 0.45 * np.cos(th) ** 2, (len(P), len(th))),
                     cap=True, co_offset=k * 3.7)
        else:
            add_tube(mb, b.pts, b.rad, sides, 0, None, cap=True, co_offset=k * 3.7)

    # --- leaves -------------------------------------------------------------
    L = sp["leaves"]
    lvls = L["levels"]
    Ps, Ts, sides_, hs = [], [], [], []
    per_m = L["per_m"] * (1.0 if detail >= 1 else 0.7)
    H, cbz = info["H"], info["crown_base"]
    for b in branches:
        if b.level not in lvls or b.kind in ("root", "stub"):
            continue
        n = int(per_m * b.length * (1.0 - L["start"]) + rng.random())
        if n <= 0:
            continue
        t = np.sort(L["start"] + (1.0 - L["start"]) * np.array([rng.random() for _ in range(n)]))
        if L["spiral"]:
            t = 1.0 - (1.0 - t) ** 1.6       # cluster towards the twig tip
        p, tan, _ = b.sample(t)
        Ps.append(p)
        Ts.append(tan)
        sides_.append(np.where(np.arange(n) % 2 == 0, 1.0, -1.0))
        hs.append(np.clip((p[:, 2] - cbz) / max(H - cbz, 1e-3), 0.0, 1.0))
    if Ps:
        P = np.concatenate(Ps)
        T = np.concatenate(Ts)
        side = np.concatenate(sides_)
        hgt = np.concatenate(hs)
        k = len(P)
        nr = np.random.default_rng(seed)
        Z = np.array([0.0, 0.0, 1.0])
        S = np.cross(T, Z)
        bad = np.linalg.norm(S, axis=1) < 1e-3
        S[bad] = np.array([1.0, 0.0, 0.0])
        S = nrm(S)
        if L["spiral"]:
            a = np.arange(k) * math.radians(137.5) + nr.normal(0, 0.4, k)
            S = S * np.cos(a)[:, None] + np.cross(T, S) * np.sin(a)[:, None]
        else:
            S = S * side[:, None]
        fwd = np.radians(L["fwd"] + nr.normal(0.0, 12.0, k))
        D = nrm(S * np.cos(fwd)[:, None] + T * np.sin(fwd)[:, None]
                + Z[None, :] * (-L["droop"] + nr.normal(0.0, 0.3, k))[:, None]
                + nr.normal(0.0, 0.18, (k, 3)))
        N0 = Z[None, :] - (D @ Z)[:, None] * D
        N0 = nrm(N0 + nr.normal(0.0, 0.05, (k, 3)))
        roll = nr.normal(0.0, 0.75, k) * (0.7 + 0.6 * hgt)
        N = nrm(N0 * np.cos(roll)[:, None] + np.cross(D, N0) * np.sin(roll)[:, None])
        P = P + D * 0.01
        size = nr.uniform(*L["size"], k) * (1.12 - 0.25 * hgt)
        shape = "beech_lo" if (L["shape"] == "beech" and leaf_detail < 2) else L["shape"]
        place_leaves(mb, leaf_template(LEAF_SHAPES[shape]), P, D, N, size,
                     fold=nr.uniform(0.15, 0.55, k), bend=nr.uniform(-0.05, 0.3, k), twist=nr.normal(0, 0.25, k),
                     mat=1, fattrs={"leaf_rand": ("FLOAT", nr.random(k)), "leaf_h": ("FLOAT", hgt)},
                     width=nr.uniform(0.85, 1.12, k))
        nleaves = k
    else:
        nleaves = 0
    me = mb.build(name, [bark_mat, leaf_mat])
    return me, info, len(branches), nleaves


