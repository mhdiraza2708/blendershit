def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser(description="1:1 iPhone 18 Pro + 24 s ad")
    ap.add_argument("--quality", choices=QUALITY.keys(), default="final",
                    help="mesh density (final = 0.3 mm outline spacing)")
    ap.add_argument("--res", default="1920x1080")
    ap.add_argument("--samples", type=int, default=12,
                    help="Cycles samples per pixel, denoised with OpenImageDenoise (raise on a GPU)")
    ap.add_argument("--noise", type=float, default=0.05, help="adaptive-sampling noise threshold")
    ap.add_argument("--threads", type=int, default=0)
    ap.add_argument("--save", default="", help="save the generated .blend here")
    ap.add_argument("--still", type=int, default=0, help="render this frame to --out")
    ap.add_argument("--frames", default="", help="render all frames as PNGs into this folder")
    ap.add_argument("--range", default="", help="frame range for --frames, e.g. 1-108")
    ap.add_argument("--edit", default="", help="folder of rendered frames to cut into the final video")
    ap.add_argument("--audio", default="", help="soundtrack .wav (generated when missing)")
    ap.add_argument("--out", default="")
    ap.add_argument("--inspect", default="", help=f"model check renders: {','.join(INSPECT_VIEWS)}")
    ap.add_argument("--outdir", default=".")
    ap.add_argument("--no-motion-blur", action="store_true")
    o = ap.parse_args(argv)
    o.res = tuple(int(v) for v in o.res.lower().split("x"))
    return o


def fresh_scene():
    scene = bpy.context.scene
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob)
    for c in list(bpy.data.collections):
        bpy.data.collections.remove(c)
    scene.name = "iPhone 18 Pro Ad"
    return scene


def build_scene(opts, ad=True):
    scene = fresh_scene()
    root = scene.collection
    setup_render(scene, opts.res, opts.samples, opts.threads, getattr(opts, "noise", 0.05))
    q = QUALITY[opts.quality]
    rig_coll = new_collection("Controls", root)
    rig = empty("PhoneRig_Ref", rig_coll)
    M = build_materials(rig)
    ph = build_phone(root, M, q)
    # the finish scan works in the phone's own space
    for n in M["fg"].nodes:
        if n.bl_idname == "ShaderNodeTexCoord":
            n.object = ph["rig"]
    bpy.data.objects.remove(rig)
    internals = build_internals(ph["coll"], ph["int_grp"], M)
    if ad:
        build_ad(scene, root, M, ph, internals)
        setup_compositor(scene)
        if opts.no_motion_blur:
            scene.render.use_motion_blur = False
    scene.render.use_persistent_data = True
    return scene, M, ph


def prepare_for_save(scene):
    """Make the saved .blend self-contained and open on a useful view."""
    for f in bpy.data.fonts:
        if f.filepath and f.packed_file is None and os.path.exists(bpy.path.abspath(f.filepath)):
            f.pack()                    # Inter is SIL OFL: fine to embed
    scene.frame_current = SHOTS["reveal"][1] - 2
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type != "VIEW_3D":
                continue
            for sp in area.spaces:
                if sp.type == "VIEW_3D":
                    sp.clip_start, sp.clip_end = 0.0005, 100.0     # the phone is 150 mm long
                    if sp.region_3d is not None:
                        sp.region_3d.view_perspective = "CAMERA"


def main():
    opts = parse_args()
    if opts.edit:
        audio = opts.audio or os.path.join(os.path.abspath(opts.edit), "soundtrack.wav")
        if not os.path.exists(audio):
            make_soundtrack(audio)
        edit_video(os.path.abspath(opts.edit), opts.out or "iphone18pro_ad.mp4", None, audio)
        return
    if opts.audio and not opts.frames and not opts.still and not opts.save:
        make_soundtrack(opts.audio)
        return
    scene, M, ph = build_scene(opts, ad=not opts.inspect)
    if opts.inspect:
        run_inspect(opts, scene, scene.collection)
    if opts.save:
        prepare_for_save(scene)
        bpy.ops.wm.save_as_mainfile(filepath=os.path.abspath(opts.save), compress=True)
        log(f"saved {opts.save}")
    if opts.still:
        scene.frame_set(opts.still)
        scene.render.filepath = os.path.abspath(opts.out or f"frame_{opts.still:04d}.png")
        t = time.time()
        bpy.ops.render.render(write_still=True)
        log(f"frame {opts.still} rendered in {time.time() - t:.1f}s -> {scene.render.filepath}")
    if opts.frames:
        d = os.path.abspath(opts.frames)
        os.makedirs(d, exist_ok=True)
        if opts.range:
            a, b = (int(v) for v in opts.range.split("-"))
            scene.frame_start, scene.frame_end = a, b
        scene.render.filepath = os.path.join(d, "frame_")
        scene.render.use_overwrite = False
        scene.render.use_placeholder = True
        t = time.time()
        bpy.ops.render.render(animation=True)
        log(f"frames {scene.frame_start}-{scene.frame_end} done in {(time.time() - t) / 60:.1f} min")


if __name__ == "__main__":
    main()
