def hexcol(h, alpha=None):
    """'#rrggbb' (sRGB) -> linear RGB(A) tuple."""
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    lin = tuple(x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c)
    return lin if alpha is None else lin + (alpha,)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def smin(a, b, k):
    h = np.clip(0.5 + 0.5 * (b - a) / k, 0.0, 1.0)
    return b * (1 - h) + a * h - k * h * (1 - h)


def box_sdf(x, y, cx, cy, hx, hy, r):
    qx = np.abs(x - cx) - (hx - r)
    qy = np.abs(y - cy) - (hy - r)
    return (np.hypot(np.maximum(qx, 0), np.maximum(qy, 0))
            + np.minimum(np.maximum(qx, qy), 0) - r)


def link(obj, coll):
    for c in obj.users_collection:
        c.objects.unlink(obj)
    coll.objects.link(obj)
    return obj


def new_collection(name, parent=None):
    c = bpy.data.collections.new(name)
    (parent or bpy.context.scene.collection).children.link(c)
    return c


def make_mesh(name, verts, faces, coll, smooth=True, sharp_angle=None, scale=MM, uvs=None):
    """verts in mm (N,3), faces = list of index sequences. Returns a new object."""
    me = bpy.data.meshes.new(name)
    v = np.asarray(verts, dtype=np.float64) * scale
    me.from_pydata(v.tolist(), [], [list(map(int, f)) for f in faces])
    me.validate(clean_customdata=False)
    if uvs is not None:
        uv = me.uv_layers.new(name="UVMap")
        lv = np.zeros(len(me.loops), dtype=np.int64)
        me.loops.foreach_get("vertex_index", lv)
        uv.data.foreach_set("uv", np.asarray(uvs, dtype=np.float32)[lv].ravel())
    ob = bpy.data.objects.new(name, me)
    coll.objects.link(ob)
    if smooth:
        me.shade_smooth()
        if sharp_angle is not None and hasattr(me, "set_sharpness_by_angle"):
            me.set_sharpness_by_angle(angle=math.radians(sharp_angle))
    return ob


def fix_normals(ob):
    bm = bmesh.new()
    bm.from_mesh(ob.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(ob.data)
    bm.free()


