def capsule_button(name, length, width, prot, coll, mat, r=0.20):
    c, s = quarter(2.0, 7)
    prof = [(0.0, -0.30), (0.0, prot - r)] + [(r * (1 - ci), prot - r + r * si) for ci, si in zip(c[1:], s[1:])]
    return slab(name, stadium(length, width, 20), prof, coll, mat=mat)


def build_lens(kind, xy, coll, par, M, seg):
    lens = empty(f"Lens_{kind}", coll, par, (xy[0], xy[1], PLAT_Z), size=0.005)
    parts = []
    c8 = [(7.74 + 0.55 * math.sin(p), 1.56 + 0.55 * math.cos(p)) for p in np.linspace(0, math.pi / 2, 9)]
    bezel = [(6.98, -0.40), (6.98, 1.40), (7.05, 1.40), (7.05, 1.95), (7.30, 2.11)] + c8 + [(LENS_R, -0.40)]
    parts.append(lathe(f"{kind}_Bezel", bezel, coll, seg=seg, closed=True, mat=M["alu_ring"]))
    parts.append(lathe(f"{kind}_Cover", [(0, 1.74), (7.03, 1.74), (7.03, 2.04), (0, 2.04)], coll,
                       seg=seg, mat=M["sapphire"], sharp_angle=30))
    lip = {"main": 5.40, "ultra": 4.45, "tele": 3.45}[kind]
    floor = {"main": -3.2, "ultra": -3.0, "tele": -2.2}[kind]
    hood = [(6.96, 1.70), (6.96, 0.95), (lip, 0.50), (lip, 0.40), (lip + 0.08, 0.40),
            (lip + 0.08, floor), (6.96, floor)]
    parts.append(lathe(f"{kind}_Hood", hood, coll, seg=seg, closed=True, mat=M["hood"], sharp_angle=30))
    er, rise = {"main": (5.30, 0.45), "ultra": (4.35, 0.55), "tele": (3.35, 0.25)}[kind]
    Rs = (er * er + rise * rise) / (2 * rise)
    dome = [(0, 0.0), (er, 0.0), (er, 0.30)] + [
        (r, 0.30 + math.sqrt(Rs * Rs - r * r) - math.sqrt(Rs * Rs - er * er)) for r in np.linspace(er, 0, 16)[1:]]
    parts.append(lathe(f"{kind}_Element", dome, coll, seg=seg, mat=M[f"element_{kind}"], sharp_angle=30))
    # deeper optics
    ir = {"main": 3.8, "ultra": 3.2, "tele": 2.6}[kind]
    inner = [(0, -1.9), (ir, -1.9), (ir, -1.7)] + [(r, -1.7 + 0.35 * (1 - (r / ir) ** 2)) for r in np.linspace(ir, 0, 10)[1:]]
    parts.append(lathe(f"{kind}_Inner", inner, coll, seg=seg // 2, mat=M[f"element_{kind}"]))
    parts.append(lathe(f"{kind}_Sensor", [(0, floor + 0.01), (lip + 0.1, floor + 0.01)], coll, seg=seg // 2, mat=M["sensor"]))
    if kind == "tele":           # the tetraprism's square window
        sq = slab("tele_Prism", lambda: rounded_outline(2.3, 2.3, 0.4, 2.0, 8, 8),
                  [(0, 1.0), (0, 1.2)], coll, mat=M["lidar"])
        sq.location.z = 0.0
        parts.append(sq)
    if kind == "ultra":
        ring = [(2.1, -0.9), (4.5, -0.9)]
        parts.append(lathe("ultra_Stop", ring, coll, seg=seg // 2, mat=M["black"]))
    parent_to(parts, lens)
    blades = []
    if kind == "main":
        q0 = np.array([IRIS_PIVOT_R, 0.0])
        beta = math.acos(4.7 / 9.0)
        th = np.linspace(IRIS_GAMMA - beta, IRIS_GAMMA + beta, 28)
        poly = np.stack([9.0 * np.cos(th), 9.0 * np.sin(th)], 1) - q0
        for i in range(IRIS_BLADES):
            h = 0.32 + i * 0.006
            v = [(p[0], p[1], 0.0) for p in poly]
            bl = make_mesh(f"IrisBlade_{i}", v, [list(range(len(v)))], coll, smooth=False)
            bl.data.materials.append(M["iris"])
            ang = 2 * math.pi * i / IRIS_BLADES
            bl.parent = lens
            bl.location = Vector((q0[0] * math.cos(ang), q0[1] + q0[0] * math.sin(ang), h)) * MM
            bl["base_angle"] = ang
            bl.rotation_euler.z = ang + iris_angle(F_STOPS[0])
            blades.append(bl)
    return lens, blades


def build_cutters(coll, M):
    cut = []
    # USB-C
    w, h = USBC["x1"] - USBC["x0"], USBC["h"]
    o = slab("cut_USBC", stadium(w, h, 20), [(0, -1.0), (0, 7.0)], coll, mat=M["port"])
    cut.append(place(o, ((USBC["x0"] + USBC["x1"]) / 2 - A, -B, 0), BOTTOM_ROT))
    for x in BOTTOM_HOLES:
        o = cylinder("cut_hole", 1.53 / 2, -1.0, 2.5, coll, seg=20, mat=M["black"])
        cut.append(place(o, (x - A, -B, 0), BOTTOM_ROT))
    for x in BOTTOM_SCREWS:
        o = cylinder("cut_screw", 1.50 / 2, -1.0, 0.6, coll, seg=24, mat=M["port"])
        cut.append(place(o, (x - A, -B, 0), BOTTOM_ROT))
    # rear mic, lens wells
    cut.append(place(cylinder("cut_mic", 1.15 / 2, -1.0, 1.4, coll, seg=20, mat=M["black"]),
                     (REAR_MIC[0], REAR_MIC[1], PLAT_Z)))
    for kind, xy in LENSES.items():
        cut.append(place(cylinder(f"cut_{kind}", 7.0, -1.0, 3.6, coll, seg=96, mat=M["black"]),
                         (xy[0], xy[1], PLAT_Z)))
    # Camera Control pocket
    cc = CAMERA_CONTROL
    o = slab("cut_camctl", stadium(cc["length"], cc["width"], 24), [(0, -0.35), (0, 1.0)], coll, mat=M["port"])
    cut.append(place(o, (cc["side"] * A, B - cc["from_top"], 0), side_rotation(cc["side"])))
    # SIM eject hole
    st = SIM_TRAY
    o = cylinder("cut_eject", 0.45, -1.0, 1.0, coll, seg=16, mat=M["black"])
    cut.append(place(o, (st["side"] * A, B - st["eject_from_top"], 0), side_rotation(st["side"])))
    return cut


def apply_booleans(ob, cutters_coll):
    mod = ob.modifiers.new("Holes", "BOOLEAN")
    mod.operation = "DIFFERENCE"
    mod.operand_type = "COLLECTION"
    mod.collection = cutters_coll
    mod.solver = "EXACT"
    try:
        mod.material_mode = "TRANSFER"
    except (AttributeError, TypeError):
        pass
    dg = bpy.context.evaluated_depsgraph_get()
    dg.update()
    t = time.time()
    me = bpy.data.meshes.new_from_object(ob.evaluated_get(dg), preserve_all_data_layers=True, depsgraph=dg)
    ob.modifiers.clear()
    old = ob.data
    ob.data = me
    bpy.data.meshes.remove(old)
    if hasattr(me, "set_sharpness_by_angle"):
        me.set_sharpness_by_angle(angle=math.radians(40))
    log(f"booleans: {len(me.vertices):,} verts after cutting ({time.time() - t:.1f}s)")


def build_phone(root_coll, M, q):
    """q: dict(spacing=mm between outline points, seg=lathe segments). Returns a dict of
    the rig, its sub-groups and the animated parts."""
    coll = new_collection("iPhone 18 Pro", root_coll)
    rig = empty("PhoneRig", coll, None, size=0.05)
    g_body = empty("Grp_Unibody", coll, rig)
    g_disp = empty("Grp_Display", coll, rig)
    g_int = empty("Grp_Internals", coll, rig)

    body = build_body(coll, q["spacing"])
    body.data.materials.append(M["alu"])
    cut_coll = new_collection("Cutters", root_coll)
    cutters = build_cutters(cut_coll, M)
    apply_booleans(body, cut_coll)
    for c in cutters:
        bpy.data.objects.remove(c)
    bpy.data.collections.remove(cut_coll)
    body.parent = g_body
    parts = []

    # Back glass window with the logo (logo lives in the shader)
    bg = BACK_GLASS
    hh = (bg["top"] - bg["bottom"]) / 2
    cy = (bg["top"] + bg["bottom"]) / 2
    nx, ny = arc_counts(bg["half_w"], hh, bg["corner"], CORNER_N, q["spacing"])
    c, s = quarter(2.0, 6)
    zt = -HT - 0.004
    prof = [(0.0, -HT + 0.30), (0.0, zt + 0.10)] + [(0.10 * (1 - ci), zt + 0.10 - 0.10 * si) for ci, si in zip(c[1:], s[1:])]

    def bg_outline():
        p, n = rounded_outline(bg["half_w"], hh, bg["corner"], CORNER_N, nx, ny)
        return p + np.array([0.0, cy]), n
    parts.append(slab("BackGlass", bg_outline, prof, coll, mat=M["back_glass"]))

    # Lenses, flash, LiDAR
    blades = []
    for kind, xy in LENSES.items():
        lens, bl = build_lens(kind, xy, coll, g_body, M, q["seg"])
        blades += bl
    for nm, xy, mat in (("Flash", FLASH, M["flash"]), ("LiDAR", LIDAR, M["lidar"])):
        e = empty(f"{nm}_Pos", coll, g_body, (xy[0], xy[1], PLAT_Z), size=0.004)
        w = lathe(nm, [(0, 0.004), (WINDOW_R, 0.004), (WINDOW_R, -0.3)], coll, seg=q["seg"], mat=mat)
        seam = lathe(f"{nm}_Seam", [(WINDOW_R, 0.002), (WINDOW_R + 0.07, 0.002)], coll, seg=q["seg"], mat=M["black"])
        parent_to([w, seam], e)

    # Buttons
    for nm, side, ft, ln, wd, prot in BUTTONS:
        b = capsule_button(nm, ln, wd, prot, coll, M["alu_btn"])
        parts.append(place(b, (side * A, B - ft, 0), side_rotation(side)))
    cc = CAMERA_CONTROL
    c, s = quarter(2.0, 6)
    prof = [(0.0, -0.34), (0.0, -0.09)] + [(0.06 * (1 - ci), -0.09 + 0.06 * si) for ci, si in zip(c[1:], s[1:])]
    o = slab("CameraControl", stadium(cc["length"] - 0.1, cc["width"] - 0.1, 24), prof, coll, mat=M["camctl"])
    parts.append(place(o, (cc["side"] * A, B - cc["from_top"], 0), side_rotation(cc["side"])))
    # SIM tray seam (a hairline ring on the flat side wall)
    st = SIM_TRAY
    po, _ = stadium(st["length"], st["width"], 24)()
    pi, _ = stadium(st["length"] - 0.12, st["width"] - 0.12, 24)()
    n = len(po)
    v = [(p[0], p[1], 0.003) for p in po] + [(p[0], p[1], 0.003) for p in pi]
    f = [(i, (i + 1) % n, n + (i + 1) % n, n + i) for i in range(n)]
    o = make_mesh("SimTraySeam", v, f, coll, smooth=False)
    o.data.materials.append(M["black"])
    parts.append(place(o, (st["side"] * A, B - st["from_top"], 0), side_rotation(st["side"])))

    # Bottom: USB-C tongue and the two pentalobe screws
    o = slab("USBC_Tongue", lambda: rounded_outline(3.3, 0.35, 0.3, 2.0, 12, 4), [(0, 2.2), (0, 6.6)], coll, mat=M["tongue"])
    parts.append(place(o, ((USBC["x0"] + USBC["x1"]) / 2 - A, -B, 0), BOTTOM_ROT))
    for x in BOTTOM_SCREWS:
        o = lathe("Screw", [(0, 0.36), (0.66, 0.36), (0.72, 0.58)], coll, seg=32, axis=1, mat=M["alu_btn"])
        th = np.linspace(0, 2 * np.pi, 60, endpoint=False)
        rr = 0.30 + 0.07 * np.cos(5 * th)
        v = [(0, 0, 0.358)] + [(r * math.cos(t), r * math.sin(t), 0.358) for r, t in zip(rr, th)]
        f = [(0, 1 + i, 1 + (i + 1) % 60) for i in range(60)]
        lobe = make_mesh("ScrewRecess", v, f, coll, smooth=False)
        lobe.data.materials.append(M["black"])
        lobe.parent = o
        parts.append(place(o, (x - A, -B, 0), BOTTOM_ROT))
    # Receiver slit on the top lip
    v = [(-RECEIVER["w"] / 2, -0.13, 0), (RECEIVER["w"] / 2, -0.13, 0), (RECEIVER["w"] / 2, 0.13, 0), (-RECEIVER["w"] / 2, 0.13, 0)]
