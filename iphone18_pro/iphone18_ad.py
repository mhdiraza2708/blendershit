    o.data.materials.append(M["black"])
    parts.append(place(o, (0, B - 1.06, LIP_Z + 0.003)))
    parent_to(parts, g_body)

    # Display stack
    nx, ny = arc_counts(A, B, CORNER_L, CORNER_N, q["spacing"])
    p0, n0 = rounded_outline(A, B, CORNER_L, CORNER_N, nx, ny)
    c, s = quarter(2.0, 12)
    gw, gz = GLASS_FLAT_D - GLASS_EDGE_D, 0.175
    prof = [(0.0, 3.75), (0.0, GLASS_TOP_Z - gz)] + [(gw * (1 - ci), GLASS_TOP_Z - gz + gz * si) for ci, si in zip(c[1:], s[1:])]
    disp = [slab("CoverGlass", lambda: (p0 - GLASS_EDGE_D * n0, n0), prof, coll, mat=M["front_glass"])]
    pb = p0 - 1.25 * n0
    o = make_mesh("DisplayBorder", np.column_stack([pb, np.full(len(pb), 3.7480)]), [list(range(len(pb)))], coll, smooth=False)
    o.data.materials.append(M["border"])
    disp.append(o)
    pa = p0 - ACTIVE_D * n0
    aw, ah = A - ACTIVE_D, B - ACTIVE_D
    uvs = np.column_stack([(pa[:, 0] + aw) / (2 * aw), (pa[:, 1] + ah) / (2 * ah)])
    o = make_mesh("Display", np.column_stack([pa, np.full(len(pa), 3.7490)]), [list(range(len(pa)))], coll,
                  smooth=False, uvs=uvs)
    o.data.materials.append(M["screen"])
    disp.append(o)
    di = DYNAMIC_ISLAND
    pd, _ = stadium(di["w"], di["h"], 24)()
