def hexcol(h, alpha=1.0):
    """'#rrggbb' in sRGB -> scene-linear RGBA tuple for node sockets."""
    h = h.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255.0
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return (out[0], out[1], out[2], alpha)


def nrm(v):
    v = np.asarray(v, dtype=np.float64)
    n = np.linalg.norm(v, axis=-1, keepdims=True)
    return v / np.maximum(n, 1e-12)


def smoothstep(e0, e1, x):
    t = np.clip((np.asarray(x, dtype=np.float64) - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def lerp(a, b, t):
    return a + (b - a) * t


class Perlin:
    """Vectorised 2D gradient noise for numpy arrays, roughly in [-1, 1]."""

    def __init__(self, seed):
        rng = np.random.default_rng(seed)
        p = rng.permutation(256)
        self.perm = np.concatenate([p, p]).astype(np.int64)
        a = rng.uniform(0.0, 2.0 * np.pi, 256)
        self.grad = np.stack([np.cos(a), np.sin(a)], axis=1)

    def noise(self, x, y):
        x = np.asarray(x, dtype=np.float64)
        y = np.asarray(y, dtype=np.float64)
        xi = np.floor(x).astype(np.int64)
        yi = np.floor(y).astype(np.int64)
        xf, yf = x - xi, y - yi
        xi &= 255
        yi &= 255
        p, g = self.perm, self.grad

        def dot(ix, iy, dx, dy):
            gr = g[p[p[ix] + iy] & 255]
            return gr[..., 0] * dx + gr[..., 1] * dy

        n00 = dot(xi, yi, xf, yf)
        n10 = dot(xi + 1, yi, xf - 1.0, yf)
        n01 = dot(xi, yi + 1, xf, yf - 1.0)
        n11 = dot(xi + 1, yi + 1, xf - 1.0, yf - 1.0)
        u = xf * xf * xf * (xf * (xf * 6.0 - 15.0) + 10.0)
        v = yf * yf * yf * (yf * (yf * 6.0 - 15.0) + 10.0)
        a = n00 + u * (n10 - n00)
        b = n01 + u * (n11 - n01)
        return (a + v * (b - a)) * 1.4

    def fbm(self, x, y, octaves=4, lacunarity=2.0, gain=0.5):
        x = np.asarray(x, dtype=np.float64)
        y = np.asarray(y, dtype=np.float64)
        total, amp, norm, f = 0.0, 1.0, 0.0, 1.0
        for i in range(octaves):
            total = total + amp * self.noise(x * f + i * 17.31, y * f - i * 9.73)
            norm += amp
            amp *= gain
            f *= lacunarity
        return total / norm


def frames_from_normals(n, yaw):
    """Rotation matrices (k,3,3) whose local Z is `n` and local X points along `yaw`."""
    n = nrm(n)
    h = np.stack([np.cos(yaw), np.sin(yaw), np.zeros_like(yaw)], axis=1)
    x = nrm(h - np.sum(h * n, axis=1, keepdims=True) * n)
    y = np.cross(n, x)
    return np.stack([x, y, n], axis=2)


def euler_xyz(R):
    """Blender XYZ Euler angles for rotation matrices R (k,3,3), R = Rz @ Ry @ Rx."""
    beta = np.arcsin(-np.clip(R[:, 2, 0], -1.0, 1.0))
    alpha = np.arctan2(R[:, 2, 1], R[:, 2, 2])
    gamma = np.arctan2(R[:, 1, 0], R[:, 0, 0])
    return np.stack([alpha, beta, gamma], axis=1)


def tilt_matrices(rng, k, amount):
    """Small random tilts as rotation matrices (k,3,3)."""
    ax = rng.normal(0.0, amount, k)
    ay = rng.normal(0.0, amount, k)
    cx, sx, cy, sy = np.cos(ax), np.sin(ax), np.cos(ay), np.sin(ay)
    Rx = np.zeros((k, 3, 3))
    Rx[:, 0, 0] = 1
    Rx[:, 1, 1], Rx[:, 1, 2], Rx[:, 2, 1], Rx[:, 2, 2] = cx, -sx, sx, cx
    Ry = np.zeros((k, 3, 3))
    Ry[:, 1, 1] = 1
    Ry[:, 0, 0], Ry[:, 0, 2], Ry[:, 2, 0], Ry[:, 2, 2] = cy, sy, -sy, cy
    return Ry @ Rx


