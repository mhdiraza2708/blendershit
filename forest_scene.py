def mat_leaves(kind, season):
    pal = LEAF_PALETTES[season]
    m, nb = new_material(f"Leaves_{kind.capitalize()}")
    rnd = nb.out(nb.attr("leaf_rand"), "Fac")
    h = nb.out(nb.attr("leaf_h"), "Fac")
