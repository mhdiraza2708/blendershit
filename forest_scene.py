    col = nb.ramp(rnd, [(0.0, c0), (0.55, c1), (1.0, c2)])
    col = nb.mix(nb.math("MULTIPLY", nb.math("POWER", h, 1.5), 0.45), col, pal[kind + "_sun"])
    col = nb.mix(nb.math("MULTIPLY", irnd, 0.3), col, nb.mix(0.5, col, "#6b6a1e"))
    r2 = nb.math("FRACT", nb.math("MULTIPLY", rnd, 7.31))
    col = nb.mix(nb.mapr(r2, 0.93, 0.965), col, pal["yellowing"])
    midrib = nb.mapr(nb.math("ABSOLUTE", nb.math("SUBTRACT", uvs.outputs["X"], 0.5)), 0.03, 0.0)
    lateral = nb.math("SINE", nb.math("MULTIPLY", nb.math("SUBTRACT", uvs.outputs["Y"], nb.math(
        "MULTIPLY", nb.math("ABSOLUTE", nb.math("SUBTRACT", uvs.outputs["X"], 0.5)), 0.9)), 50.0))
    veins = nb.math("MAXIMUM", midrib, nb.math("MULTIPLY", nb.mapr(lateral, 0.9, 1.0), 0.6))
    col = nb.mix(nb.math("MULTIPLY", veins, 0.22), col, nb.mix(0.5, col, "#c8d27a"))
    front = nb.principled(base=col, rough=0.45, spec=0.4)
    trans_col = nb.mix(0.55, col, pal[kind + "_tr"])
    trans_col = nb.mix(nb.math("MULTIPLY", veins, 0.5), trans_col, nb.mix(0.6, trans_col, "#3d4a10"))
    trans = nb.node("ShaderNodeBsdfTranslucent", {"Color": trans_col})
    shader = nb.node("ShaderNodeMixShader", {0: 0.4, 1: front, 2: trans})
    nb.output(shader)
    return m


