def area_light(name, coll, loc, target, size, energy, color=(1, 1, 1), shape="RECTANGLE", size_y=None, spread=None):
    ld = bpy.data.lights.new(name, "AREA")
    ld.shape = shape
    ld.size = size
    if size_y is not None:
        ld.size_y = size_y
    ld.energy = energy
    ld.color = color
    if spread is not None:
        ld.spread = spread
    ob = bpy.data.objects.new(name, ld)
