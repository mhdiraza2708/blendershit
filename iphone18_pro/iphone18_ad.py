class NB:
    """Tiny helper to build node trees tersely."""

    def __init__(self, tree):
        self.tree, self.nodes, self.links = tree, tree.nodes, tree.links

    @staticmethod
    def sock(sockets, key):
        if isinstance(key, int):
            return sockets[key]
        for k in (key, _SOCKET_ALIASES.get(key)):
            if k is None:
                continue
            for s in sockets:
                if s.identifier == k:
                    return s
            match = [s for s in sockets if s.name == k]
            for s in match:
                if s.enabled:
                    return s
            if match:
                return match[0]
        raise KeyError(f"socket {key!r} not in {[s.name for s in sockets]}")

    def out(self, x, key=None):
        if isinstance(x, bpy.types.NodeSocket):
            return x
        if key is not None:
            return self.sock(x.outputs, key)
        for s in x.outputs:
            if s.enabled:
                return s
        return x.outputs[0]

    def set(self, node, key, value):
        s = self.sock(node.inputs, key)
        if isinstance(value, (bpy.types.NodeSocket, bpy.types.Node)):
            self.links.new(self.out(value), s)
            return
        if isinstance(value, str):
            value = hexcol(value)
        dv = s.default_value
        if hasattr(dv, "__len__"):
            if isinstance(value, (int, float)):
                value = (value,) * len(dv)
                if len(dv) == 4:
                    value = value[:3] + (1.0,)
            elif len(value) == 3 and len(dv) == 4:
                value = tuple(value) + (1.0,)
        s.default_value = value

    def node(self, idname, inputs=None, **props):
        n = self.nodes.new(idname)
        for k, v in props.items():
            setattr(n, k, v)
        for k, v in (inputs or {}).items():
            self.set(n, k, v)
        return n

    def math(self, op, a, b=0.0, clamp=False):
        n = self.node("ShaderNodeMath", operation=op, use_clamp=clamp)
        self.set(n, 0, a)
        self.set(n, 1, b)
        return n.outputs[0]

    def vmath(self, op, a, b=None, scale=None):
        n = self.node("ShaderNodeVectorMath", operation=op)
        self.set(n, 0, a)
        if b is not None:
            self.set(n, 1, b)
        if scale is not None:
            self.set(n, "Scale", scale)
        return n.outputs[0] if op not in ("DOT_PRODUCT", "LENGTH", "DISTANCE") else n.outputs[1]

    def mapr(self, v, a, b, c=0.0, d=1.0, clamp=True, interp="LINEAR"):
        n = self.node("ShaderNodeMapRange", clamp=clamp, interpolation_type=interp)
        for k, val in (("Value", v), ("From Min", a), ("From Max", b), ("To Min", c), ("To Max", d)):
            self.set(n, k, val)
        return self.sock(n.outputs, "Result")

    def mix(self, fac, a, b, blend="MIX"):
        n = self.node("ShaderNodeMix", data_type="RGBA", blend_type=blend)
        self.set(n, "Factor_Float", fac)
        self.set(n, "A_Color", a)
        self.set(n, "B_Color", b)
        return self.sock(n.outputs, "Result_Color")

    def mixf(self, fac, a, b):
        n = self.node("ShaderNodeMix", data_type="FLOAT")
        self.set(n, "Factor_Float", fac)
        self.set(n, "A_Float", a)
        self.set(n, "B_Float", b)
        return self.sock(n.outputs, "Result_Float")

    def ramp(self, fac, stops, interp="LINEAR"):
        n = self.node("ShaderNodeValToRGB")
        cr = n.color_ramp
        cr.interpolation = interp
        conv = [(p, hexcol(c, 1.0) if isinstance(c, str) else c) for p, c in stops]
        cr.elements[0].position, cr.elements[0].color = conv[0]
        cr.elements[1].position, cr.elements[1].color = conv[-1]
        for p, c in conv[1:-1]:
            cr.elements.new(p).color = c
        self.set(n, 0, fac)
        return n.outputs[0]

    def sep(self, vec):
        n = self.node("ShaderNodeSeparateXYZ")
        self.set(n, 0, vec)
        return n

    def comb(self, x, y, z):
        return self.node("ShaderNodeCombineXYZ", {0: x, 1: y, 2: z}).outputs[0]

    def principled(self, **kw):
        names = {"base": "Base Color", "metal": "Metallic", "rough": "Roughness", "normal": "Normal",
                 "spec": "Specular IOR Level", "ior": "IOR", "trans": "Transmission Weight",
                 "coat": "Coat Weight", "coat_rough": "Coat Roughness", "emit": "Emission Color",
                 "emit_str": "Emission Strength", "alpha": "Alpha", "aniso": "Anisotropic",
                 "film": "Thin Film Thickness", "film_ior": "Thin Film IOR", "sheen": "Sheen Weight"}
        n = self.node("ShaderNodeBsdfPrincipled")
        for k, v in kw.items():
            try:
                self.set(n, names[k], v)
            except KeyError:            # e.g. thin film needs Blender 4.2+
                pass
        return n

    def output(self, surface):
        o = self.node("ShaderNodeOutputMaterial")
        self.set(o, "Surface", surface)
        return o


def new_material(name):
    m = bpy.data.materials.new(name)
    if not BLENDER_5:
        m.use_nodes = True
    m.node_tree.nodes.clear()
    return m, NB(m.node_tree)


def new_group(name, outputs):
    ng = bpy.data.node_groups.new(name, "ShaderNodeTree")
    for nm, typ in outputs:
        ng.interface.new_socket(nm, in_out="OUTPUT", socket_type=typ)
    nb = NB(ng)
    return ng, nb, nb.node("NodeGroupOutput")


def use_group(nb, ng):
    n = nb.node("ShaderNodeGroup")
    n.node_tree = ng
    return n


