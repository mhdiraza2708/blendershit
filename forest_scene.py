_ATTR_WIDTH = {"FLOAT": 1, "INT": 1, "FLOAT_VECTOR": 3, "FLOAT_COLOR": 4}
_ATTR_KEY = {"FLOAT": "value", "INT": "value", "FLOAT_VECTOR": "vector", "FLOAT_COLOR": "color"}


def set_attribute(me, name, values, domain, kind):
    attr = me.attributes.new(name=name, type=kind, domain=domain)
    dtype = np.int32 if kind == "INT" else np.float32
    attr.data.foreach_set(_ATTR_KEY[kind], np.ascontiguousarray(values, dtype=dtype).ravel())


def mesh_from_arrays(name, verts, faces_flat, sizes):
    me = bpy.data.meshes.new(name)
    verts = np.ascontiguousarray(verts, dtype=np.float32).reshape(-1)
    faces_flat = np.ascontiguousarray(faces_flat, dtype=np.int32)
    sizes = np.ascontiguousarray(sizes, dtype=np.int32)
    me.vertices.add(len(verts) // 3)
    me.vertices.foreach_set("co", verts)
    if len(sizes):
        starts = np.zeros(len(sizes), dtype=np.int32)
        starts[1:] = np.cumsum(sizes)[:-1]
        me.loops.add(len(faces_flat))
        me.loops.foreach_set("vertex_index", faces_flat)
        me.polygons.add(len(sizes))
        me.polygons.foreach_set("loop_start", starts)
        if bpy.app.version < (4, 0, 0):
            me.polygons.foreach_set("loop_total", sizes)
    me.update(calc_edges=True)
    return me


def set_smooth(me):
    try:
        me.shade_smooth()
    except AttributeError:
        me.polygons.foreach_set("use_smooth", np.ones(len(me.polygons), dtype=bool))


class MeshBuilder:
    """Accumulates vertices and faces (with per-loop UVs, material indices and
    custom attributes) from many numpy chunks, then builds one Blender mesh."""

    def __init__(self):
        self.verts, self.vattr = [], []
        self.faces, self.uvs, self.mats, self.fattr = [], [], [], []
        self.nv = 0

    def add_verts(self, verts, attrs=None):
        verts = np.asarray(verts, dtype=np.float64).reshape(-1, 3)
        base = self.nv
        self.verts.append(verts)
        self.vattr.append(attrs or {})
        self.nv += len(verts)
        return base

    def add_faces(self, faces, uvs=None, mat=0, attrs=None):
        faces = np.asarray(faces, dtype=np.int64)
        if faces.ndim == 1:
            faces = faces[None]
        if uvs is None:
            uvs = np.zeros(faces.shape + (2,))
        self.faces.append(faces)
        self.uvs.append(np.asarray(uvs, dtype=np.float64).reshape(faces.shape + (2,)))
        self.mats.append(np.full(len(faces), mat, dtype=np.int32))
        self.fattr.append(attrs or {})

    def add(self, verts, faces, uvs=None, mat=0, vattrs=None, fattrs=None):
        base = self.add_verts(verts, vattrs)
        self.add_faces(np.asarray(faces) + base, uvs, mat, fattrs)
        return base

    @staticmethod
    def _gather(chunks, counts):
        kinds = {}
        for c in chunks:
            for k, (kind, _) in c.items():
                kinds[k] = kind
        out = {}
        for name, kind in kinds.items():
            w = _ATTR_WIDTH[kind]
            parts = []
            for c, n in zip(chunks, counts):
                shape = (n,) if w == 1 else (n, w)
                if name in c:
                    parts.append(np.broadcast_to(np.asarray(c[name][1], dtype=np.float64), shape))
                else:
                    parts.append(np.zeros(shape))
            out[name] = (kind, np.concatenate(parts))
        return out

    def build(self, name, materials=(), smooth=True):
        V = np.concatenate(self.verts) if self.verts else np.zeros((0, 3))
        if self.faces:
            sizes = np.concatenate([np.full(len(f), f.shape[1], dtype=np.int32) for f in self.faces])
            flat = np.concatenate([f.ravel() for f in self.faces])
        else:
            sizes = np.zeros(0, dtype=np.int32)
            flat = np.zeros(0, dtype=np.int32)
        me = mesh_from_arrays(name, V, flat, sizes)
        if self.faces:
            uvl = me.uv_layers.new(name="UVMap")
            uvl.data.foreach_set("uv", np.concatenate([u.reshape(-1, 2) for u in self.uvs]).astype(np.float32).ravel())
            me.polygons.foreach_set("material_index", np.concatenate(self.mats))
        for nm, (kind, arr) in self._gather(self.vattr, [len(v) for v in self.verts]).items():
            set_attribute(me, nm, arr, "POINT", kind)
        for nm, (kind, arr) in self._gather(self.fattr, [len(f) for f in self.faces]).items():
            set_attribute(me, nm, arr, "FACE", kind)
        for m in materials:
            me.materials.append(m)
        if smooth and self.faces:
            set_smooth(me)
        me.update()
        return me


def tube(pts, rad, sides, radial=None, cap=True, co_offset=0.0):
    """Tapered tube along a polyline.

    Returns (verts, quads, quad_uvs, tris, tri_uvs, bark_co). `bark_co` is a
    seamless per-vertex texture coordinate: (r cos a, r sin a, arc length).
    `radial(theta, P)` may return an (n, sides) radius multiplier."""
    P = np.asarray(pts, dtype=np.float64)
    R = np.asarray(rad, dtype=np.float64)
    n = len(P)
    T = np.empty_like(P)
    T[1:-1] = P[2:] - P[:-2]
    T[0] = P[1] - P[0]
    T[-1] = P[-1] - P[-2]
    T = nrm(T)
    m = nrm(P[-1] - P[0])
    ref = np.array([1.0, 0.0, 0.0]) if abs(m[2]) > 0.9 else np.array([0.0, 0.0, 1.0])
    N = nrm(ref[None, :] - (T @ ref)[:, None] * T)
    B = np.cross(T, N)
    th = np.arange(sides) * (2.0 * np.pi / sides)
    ct, st = np.cos(th), np.sin(th)
    ring = ct[None, :, None] * N[:, None, :] + st[None, :, None] * B[:, None, :]
    rr = np.repeat(R[:, None], sides, axis=1)
    if radial is not None:
        rr = rr * radial(th, P)
    V = (P[:, None, :] + rr[..., None] * ring).reshape(-1, 3)
    s = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(P, axis=0), axis=1))])
    co = np.stack([R[:, None] * ct[None, :], R[:, None] * st[None, :],
                   np.repeat(s[:, None] + co_offset, sides, axis=1)], axis=-1).reshape(-1, 3)

    i = np.arange(n - 1)[:, None]
    j = np.arange(sides)[None, :]
    j1 = (j + 1) % sides
    quads = np.stack([i * sides + j, i * sides + j1, (i + 1) * sides + j1, (i + 1) * sides + j], -1).reshape(-1, 4)
    circ = 2.0 * np.pi * max(R[0], 1e-3)
    u0 = np.broadcast_to(j / sides, (n - 1, sides))
    u1 = np.broadcast_to((j + 1) / sides, (n - 1, sides))
    v0 = np.broadcast_to(s[:-1, None] / circ, (n - 1, sides))
    v1 = np.broadcast_to(s[1:, None] / circ, (n - 1, sides))
    quv = np.stack([np.stack([u0, v0], -1), np.stack([u1, v0], -1),
                    np.stack([u1, v1], -1), np.stack([u0, v1], -1)], axis=2).reshape(-1, 4, 2)
    tris, tuv = None, None
    if cap:
        tip = P[-1] + T[-1] * R[-1] * 0.8
        k = len(V)
        V = np.vstack([V, tip])
        co = np.vstack([co, [0.0, 0.0, s[-1] + co_offset + R[-1]]])
        last = (n - 1) * sides
        jj = np.arange(sides)
        tris = np.stack([last + jj, last + (jj + 1) % sides, np.full(sides, k)], -1)
        vt = s[-1] / circ
        tuv = np.stack([np.stack([jj / sides, np.full(sides, vt)], -1),
                        np.stack([(jj + 1) / sides, np.full(sides, vt)], -1),
                        np.stack([(jj + 0.5) / sides, np.full(sides, vt + 0.05)], -1)], axis=1)
    return V, quads, quv, tris, tuv, co


def add_tube(mb, pts, rad, sides, mat=0, radial=None, cap=True, co_offset=0.0, fattrs=None):
    V, Q, QUV, Tr, TUV, co = tube(pts, rad, sides, radial, cap, co_offset)
    base = mb.add_verts(V, {"bark_co": ("FLOAT_VECTOR", co)})
    mb.add_faces(Q + base, QUV, mat, fattrs)
    if Tr is not None:
        mb.add_faces(Tr + base, TUV, mat, fattrs)


def leaf_template(rows):
    """Triangulated leaf blade. `rows` = [(x, half_width), ...] between the base
    (x=0) and the tip (x=1). Returns local verts (k,3), tris (m,3), uvs (k,2)."""
    V = [(0.0, 0.0, 0.0)]
    for x, w in rows:
        V += [(x, w, 0.0), (x, 0.0, 0.0), (x, -w, 0.0)]      # left, midrib, right
    V.append((1.0, 0.0, 0.0))
    tris = [(0, 3, 2), (0, 2, 1)]
    for k in range(len(rows) - 1):
        L, M, R = 1 + 3 * k, 2 + 3 * k, 3 + 3 * k
        L2, M2, R2 = L + 3, M + 3, R + 3
        tris += [(R, R2, M2), (R, M2, M), (M, M2, L2), (M, L2, L)]
    k = len(rows) - 1
    L, M, R = 1 + 3 * k, 2 + 3 * k, 3 + 3 * k
    tip = len(V) - 1
    tris += [(R, tip, M), (M, tip, L)]
    V = np.array(V)
    wmax = max(w for _, w in rows)
    uv = np.stack([0.5 + V[:, 1] / (2.0 * wmax), V[:, 0]], axis=1)
    return V, np.array(tris), uv


