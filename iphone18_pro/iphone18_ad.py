def _font(style):
    for p in FONT_FILES[style]:
        if os.path.exists(p):
            return bpy.data.fonts.load(p, check_existing=True)
    return None


def _new_effect(strips, name, typ, channel, start, end):
    try:
        return strips.new_effect(name, type=typ, channel=channel, frame_start=start, length=end - start + 1)
    except TypeError:
        return strips.new_effect(name, type=typ, channel=channel, frame_start=start, frame_end=end + 1)


def edit_video(frames_dir, out, res, audio=None):
    files = sorted(f for f in os.listdir(frames_dir) if f.startswith("frame_") and f.endswith(".png"))
    if not files:
        raise SystemExit(f"no frames in {frames_dir}")
    if res is None:
        img = bpy.data.images.load(os.path.join(frames_dir, files[0]))
        res = tuple(img.size)
        bpy.data.images.remove(img)
    sc = bpy.data.scenes.new("Edit")
    sc.render.fps = FPS
    sc.render.resolution_x, sc.render.resolution_y = res
    sc.render.resolution_percentage = 100
    sc.frame_start, sc.frame_end = 1, len(files)
    se = sc.sequence_editor_create()
    strips = se.strips if hasattr(se, "strips") else se.sequences
    pic = strips.new_image("frames", os.path.join(frames_dir, files[0]), 1, 1)
    for f in files[1:]:
        pic.elements.append(f)
    k = res[1] / 1080.0
    for i, (a, b, text, size, x, y, style, fade) in enumerate(TITLES):
        if a > len(files):
            continue
        b = min(b, len(files))
        st = _new_effect(strips, f"T{i:02d}", "TEXT", 3 + i % 4, a, b)
        st.text = text
        st.font_size = size * k
        fnt = _font(style)
        if fnt is not None:
            st.font = fnt
        st.color = (1, 1, 1, 1) if style == "bold" else (0.80, 0.80, 0.83, 1)
        st.location = (x, y)
        for prop, val in (("anchor_x", "LEFT"), ("anchor_y", "CENTER"), ("alignment_x", "LEFT")):
            if hasattr(st, prop):
                setattr(st, prop, val)
        st.use_shadow = True
        if hasattr(st, "shadow_blur"):
            st.shadow_blur = 0.6
            st.shadow_offset = 0.0
        st.shadow_color = (0, 0, 0, 0.55)
        st.blend_type = "ALPHA_OVER"
        if fade:
            kfs(st, "blend_alpha", [(a, 0.0), (a + fade, 1.0), (b - fade, 1.0), (b, 0.0)], interp="LINEAR")
    # fade to black over the last half second
    blk = _new_effect(strips, "FadeOut", "COLOR", 8, len(files) - 12, len(files))
    blk.color = (0, 0, 0)
    blk.blend_type = "ALPHA_OVER"
    kfs(blk, "blend_alpha", [(len(files) - 12, 0.0), (len(files), 1.0)], interp="LINEAR")
    if audio and os.path.exists(audio):
        snd = strips.new_sound("soundtrack", audio, 9, 1)
        snd.volume = 1.0
    im = sc.render.image_settings
    if hasattr(im, "media_type"):
        im.media_type = "VIDEO"
    im.file_format = "FFMPEG"
    ff = sc.render.ffmpeg
    ff.format, ff.codec = "MPEG4", "H264"
    ff.constant_rate_factor = "HIGH"
    ff.ffmpeg_preset = "GOOD"
    if audio:
        ff.audio_codec = "AAC"
        ff.audio_bitrate = 192
        ff.audio_channels = "STEREO"
        ff.audio_mixrate = SR
    sc.view_settings.view_transform = "Standard"
    sc.view_settings.look = "None"
    sc.render.filepath = os.path.abspath(out)
    sc.render.use_file_extension = False
    log(f"editing {len(files)} frames -> {out}")
    bpy.ops.render.render(animation=True, scene=sc.name)
    log(f"wrote {out}")


