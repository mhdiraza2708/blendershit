TRAY_FLOOR_Z = -HT + 0.78


def body_profile():
    """(d, z, kind) from the hidden front floor, over the lip, down the side and
    across the back. d = inset from the outline, z in mm. kind: 'f' front, 's' side,
    'b' back round, 'p' back plane."""
    # the unibody is a tray: floor 0.78 inside the back, 1.22 frame wall up to the lip
    P = [(1.95, TRAY_FLOOR_Z, "f"), (1.40, TRAY_FLOOR_Z + 0.12, "f"), (1.24, TRAY_FLOOR_Z + 0.45, "f"),
         (1.22, TRAY_FLOOR_Z + 0.9, "f"), (1.22, 4.10, "f"), (1.22, LIP_Z, "f"), (1.06, LIP_Z, "f")]
    c, s = quarter(2.4, 11)                       # front round (0.90 x 1.245)
    for ci, si in zip(c, s):
        P.append((LIP_D - LIP_D * si, 2.99 + (LIP_Z - 2.99) * ci, "f"))
    zs = np.concatenate([np.linspace(2.99, 0.6, 6)[1:], np.linspace(0.6, -2.86, 8)[1:]])
    for z in zs:
        P.append((0.0, float(z), "s"))
    c, s = quarter(2.65, 19)                      # back round (3.79 x 1.52)
    for ci, si in zip(c[1:], s[1:]):
        P.append((BACK_ROUND_D - BACK_ROUND_D * ci, -2.86 - BACK_ROUND_Z * si, "b"))
    P.append((5.5, -HT, "p"))
    # de-duplicate
    out = []
    for p in P:
        if not out or abs(out[-1][0] - p[0]) + abs(out[-1][1] - p[1]) > 1e-6:
            out.append(p)
    return out


def build_body(coll, spacing):
    nx, ny = arc_counts(A, B, CORNER_L, CORNER_N, spacing)
    pts, nrm = rounded_outline(A, B, CORNER_L, CORNER_N, nx, ny)
    N = len(pts)
    prof = body_profile()
    rings = []
    for d, z, kind in prof:
        p = pts - d * nrm
        if kind in ("s", "b", "p"):
            h = plateau_height(p[:, 0], p[:, 1])
            if kind == "b":
                dd = d * (1.0 + 0.30 * h / PLAT_H)   # the plateau's top edge rounds a bit wider
                p = pts - dd[:, None] * nrm
            w = 1.0 if kind != "s" else float(smoothstep(-0.2, -2.86, z))
            zz = z - h * w
        else:
            zz = np.full(N, z)
        rings.append(np.column_stack([p, zz]))
    verts = [r for r in rings]
    nr = len(rings)
    faces = []
    ii = np.arange(N)
    for k in range(nr - 1):
        a0, a1 = k * N + ii, k * N + (ii + 1) % N
        b0, b1 = (k + 1) * N + ii, (k + 1) * N + (ii + 1) % N
        faces.extend(np.stack([a0, a1, b1, b0], 1).tolist())
    # tray floor: one flat n-gon
    faces.append(list(range(N))[::-1])
    # back: Coons grid inside the last ring, heights from the plateau field
    last = rings[-1][:, :2]
    g, gidx = coons_grid(last, nx, ny)
    base = nr * N
    interior = gidx < 0
    gi = -np.ones_like(gidx)
    gi[~interior] = gidx[~interior] + (nr - 1) * N
    nint = int(interior.sum())
    gi[interior] = base + np.arange(nint)
    gp = g[interior]
    gz = -HT - plateau_height(gp[:, 0], gp[:, 1])
    verts.append(np.column_stack([gp, gz]))
    q = np.stack([gi[:-1, :-1], gi[1:, :-1], gi[1:, 1:], gi[:-1, 1:]], -1).reshape(-1, 4)
    faces.extend(q[:, ::-1].tolist())
    ob = make_mesh("Unibody", np.vstack(verts), faces, coll, sharp_angle=40)
    fix_normals(ob)
    for poly in ob.data.polygons:          # the planar tray floor
        if poly.loop_total > 4:
            poly.use_smooth = False
    log(f"body: {len(ob.data.vertices):,} verts ({nx}x{ny} per ring, {nr} rings)")
    return ob


