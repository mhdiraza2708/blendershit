def prepare_scene():
    if bpy.context.window is not None:
        scene = bpy.data.scenes.new("Forest")
        bpy.context.window.scene = scene
    else:
        scene = bpy.context.scene
        for ob in list(scene.objects):
            bpy.data.objects.remove(ob, do_unlink=True)
        for c in list(scene.collection.children):
            scene.collection.children.unlink(c)
        try:
            bpy.data.orphans_purge(do_recursive=True)
        except Exception:
            pass
        scene.name = "Forest"
    return scene


def make_collection(name, parent):
    c = bpy.data.collections.new(name)
    parent.children.link(c)
    return c


def build_forest(opts):
    rng = random.Random(opts.seed)
    nrng = np.random.default_rng(opts.seed)
    scene = prepare_scene()
    root = make_collection("Forest", scene.collection)
    assets = make_collection("Forest Assets", scene.collection)
    c_env = make_collection("Terrain & Sky", root)
    c_trees = make_collection("Trees", root)
    c_ground = make_collection("Ground Cover", root)
    c_props = make_collection("Rocks & Logs", root)

    path = FootPath(PATH_POINTS, PATH_HALF_WIDTH)
    terrain = Terrain(opts.seed, path)
    animate = bool(getattr(opts, "animate", None))
    track = None
    if animate:
        frames = max(2, int(round(opts.animate * opts.fps)))
        track = camera_track(terrain, path, frames, opts.fps, opts.speed, opts.seed)
        scene.frame_start, scene.frame_end = 1, frames
        scene.render.fps = opts.fps
        log(f"camera move: {frames} frames, {opts.speed * (frames - 1) / opts.fps:.1f} m along the path")
    cam = setup_camera(c_env, terrain, track)
    scene.camera = cam
    view = View.from_camera(cam, opts.res)
    tan_h = view.tan_h
    if track:        # scatter must cover what the camera sees anywhere along its move
        poses = track[::max(1, opts.fps // 2)] + [track[-1]]
        views = ViewSet([View(loc, rot.to_matrix(), tan_h, opts.res[1] / opts.res[0]) for loc, rot in poses])
    else:
        views = ViewSet([view])
    to_sun = sun_vector(LOOK["sun_azimuth"], LOOK["sun_elevation"], view.heading)
    shade_dir = Vector((-to_sun.x, -to_sun.y, 0.0)).normalized()
    shade = tuple(shade_dir)

    log("materials")
    M = dict(ground=mat_ground(opts.season), beech=mat_bark_beech(shade), oak=mat_bark_oak(shade),
             leaf_beech=mat_leaves("beech", opts.season), leaf_oak=mat_leaves("oak", opts.season),
             leaf_sapling=mat_leaves("sapling", opts.season), fern=mat_fern(opts.season),
             grass=mat_grass(opts.season), litter=mat_litter(opts.season), deadwood=mat_deadwood(),
             rock=mat_rock(), log=mat_log(shade))

    build_terrain(terrain, M["ground"], c_env, LOOK["cam_xy"])
    obstacles = Obstacles()

    # --- hero elements near the camera ----------------------------------------------
    cx, cy = LOOK["cam_xy"]
    hero_xy = (cx - 2.7, cy + 4.6)
    me, info, nb_, nl_ = tree_mesh("Hero_Beech", SPECIES["beech"], opts.seed * 1000 + 1, 2,
                                   M["beech"], M["leaf_beech"], scale=1.12)
    hero = new_object("Hero_Beech", me, c_trees)
    hz = float(terrain.height(np.array([hero_xy[0]]), np.array([hero_xy[1]]))[0])
    hero.location = (hero_xy[0], hero_xy[1], hz - 0.12)
    hero.rotation_euler = (0.0, 0.0, rng.uniform(0, 2 * math.pi))
    obstacles.add(hero_xy[0], hero_xy[1], info["R"] * 2.2)
    log(f"hero beech: {nb_} branches, {nl_:,} leaves")

    log_obj, log_pts = build_log(terrain, M["log"], c_props, rng, (cx + 2.2, cy + 7.2), (cx + 8.6, cy + 12.8), 0.3)
    obstacles.add(log_pts[:, 0], log_pts[:, 1], np.full(len(log_pts), 0.45))

    # --- tree assets --------------------------------------------------------------
    detail = opts.detail
    tree_colls = {}
    for sp_name, count in (("beech", 6), ("oak", 3)):
        coll = make_collection(f"Assets {sp_name}", assets)
        for i in range(count):
            me, info, nb_, nl_ = tree_mesh(f"{sp_name}_{i:02d}", SPECIES[sp_name], opts.seed * 100 + i * 7 + len(sp_name),
                                           detail, M[sp_name], M["leaf_" + sp_name], leaf_detail=1)
            new_object(f"{sp_name}_{i:02d}", me, coll)
            log(f"{sp_name} {i}: {info['H']:.1f} m, {nb_} branches, {nl_:,} leaves")
        tree_colls[sp_name] = (coll, count)

    # --- forest layout -------------------------------------------------------------
    # plant the whole view cone (plus margins for shadows) so the forest never visibly ends
    pts = poisson_disk(rng, cx - 270.0, cx + 270.0, cy - 30.0, cy + 380.0, 6.3)
    pts = pts[(views.distance(pts[:, 0], pts[:, 1]) < 70.0) | views.in_cone(pts[:, 0], pts[:, 1], 0.45)]
    d_path = path.distance(pts[:, 0], pts[:, 1])
    keep = (d_path > 2.3) & (obstacles.clearance(pts[:, 0], pts[:, 1]) > 3.0)
    keep &= views.distance(pts[:, 0], pts[:, 1]) > 3.5
    # irregular canopy gaps let shafts of sunlight into the stand
    gaps = Perlin(opts.seed + 5).fbm(pts[:, 0] / 28.0, pts[:, 1] / 28.0, 2)
    keep &= gaps > -0.28
    pts = pts[keep]
    species_noise = Perlin(opts.seed + 3).fbm(pts[:, 0] / 45.0, pts[:, 1] / 45.0, 2)
    is_oak = (species_noise + nrng.normal(0, 0.25, len(pts))) > 0.32
    for sp_name, sel in (("beech", ~is_oak), ("oak", is_oak)):
        P = pts[sel]
        k = len(P)
        z = terrain.height(P[:, 0], P[:, 1]) - 0.12
        coll, count = tree_colls[sp_name]
        rot = np.stack([nrng.normal(0, 0.015, k), nrng.normal(0, 0.015, k), nrng.uniform(0, 2 * np.pi, k)], axis=1)
        s = nrng.uniform(0.85, 1.12, k)
        scatter_object(f"Trees_{sp_name}", np.column_stack([P, z]), rot, np.repeat(s[:, None], 3, axis=1),
                       nrng.integers(0, count, k), c_trees, coll, viewport_fraction=0.2)
        obstacles.add(P[:, 0], P[:, 1], np.full(k, 0.55))

    # --- saplings ----------------------------------------------------------------
    coll = make_collection("Assets saplings", assets)
    ns = 6
    for i in range(ns):
        me, info, _, nl_ = tree_mesh(f"sapling_{i:02d}", SPECIES["sapling"], opts.seed * 50 + i, max(detail, 1),
                                     M["beech"], M["leaf_sapling"], leaf_detail=2)
        new_object(f"sapling_{i:02d}", me, coll)
    x, y, r = views.sample(nrng, 0.08 * opts.density, 2.5, 90.0, 0.35)
    d = path.distance(x, y)
    patch = Perlin(opts.seed + 9).fbm(x / 18.0, y / 18.0, 3)
    clear = (2.6, 4.0) if animate else (1.3, 2.5)      # a moving camera must not brush through leaves
    prob = smoothstep(-0.2, 0.3, patch) * smoothstep(*clear, d) * smoothstep(0.3, 1.2, obstacles.clearance(x, y))
    # keep the middle of the frame open near the camera: close saplings only frame the edges
    for v in views.views:
        near_v = np.hypot(x - v.pos[0], y - v.pos[1]) < 14.0
        prob *= np.where(near_v, smoothstep(0.42, 0.6, v.off_axis(x, y)), 1.0)
    prob *= smoothstep(4.0, 7.0, r)
    sel = nrng.random(len(x)) < prob
    x, y, d = x[sel], y[sel], d[sel]
    k = len(x)
    z = terrain.height(x, y, d) - 0.03
    rot = np.stack([nrng.normal(0, 0.05, k), nrng.normal(0, 0.05, k), nrng.uniform(0, 2 * np.pi, k)], axis=1)
    s = np.exp(nrng.normal(0.1, 0.35, k)).clip(0.6, 2.2) * np.clip(r[sel] / 14.0, 0.55, 1.0)
    scatter_object("Saplings", np.column_stack([x, y, z]), rot, np.repeat(s[:, None], 3, axis=1),
                   nrng.integers(0, ns, k), c_ground, coll, 0.5)

    # --- ferns -----------------------------------------------------------------
    coll = make_collection("Assets ferns", assets)
    nf = 8
    for i in range(nf):
        new_object(f"fern_{i:02d}", build_fern(rng, detail, M["fern"]), coll)
    x, y, r = views.sample(nrng, 2.4 * opts.density, 0.8, 60.0, 0.3)
    d = path.distance(x, y)
    patch = Perlin(opts.seed + 21).fbm(x / 8.0, y / 8.0, 3)
    prob = (smoothstep(-0.05, 0.3, patch) * smoothstep(1.0, 1.7, d) * smoothstep(0.1, 0.6, obstacles.clearance(x, y))
            * (1.0 - smoothstep(45.0, 60.0, r)))
    sel = nrng.random(len(x)) < prob
    x, y, d = x[sel], y[sel], d[sel]
    k = len(x)
    z = terrain.height(x, y, d) - 0.02
    rot = np.stack([nrng.normal(0, 0.08, k), nrng.normal(0, 0.08, k), nrng.uniform(0, 2 * np.pi, k)], axis=1)
    s = nrng.uniform(0.7, 1.3, k)
    scatter_object("Ferns", np.column_stack([x, y, z]), rot, np.repeat(s[:, None], 3, axis=1),
                   nrng.integers(0, nf, k), c_ground, coll, 0.5)

    # --- grass tufts ------------------------------------------------------------
    coll = make_collection("Assets grass", assets)
    ng_ = 6
    for i in range(ng_):
        new_object(f"grass_{i:02d}", build_grass(rng, M["grass"], rng.randint(30, 70), rng.uniform(0.25, 0.55)), coll)
    x, y, r = views.sample(nrng, 3.0 * opts.density, 0.6, 40.0, 0.3)
    d = path.distance(x, y)
    patch = Perlin(opts.seed + 33).fbm(x / 5.0, y / 5.0, 3)
    band = np.exp(-((d - PATH_HALF_WIDTH * 1.5) / 0.55) ** 2)
    prob = (0.8 * band * smoothstep(-0.2, 0.2, patch) + 0.25 * smoothstep(0.35, 0.55, patch)) * smoothstep(0.55, 0.8, d) \
        * smoothstep(0.1, 0.4, obstacles.clearance(x, y)) * (1.0 - smoothstep(30.0, 40.0, r))
    sel = nrng.random(len(x)) < prob
    x, y, d = x[sel], y[sel], d[sel]
    k = len(x)
    z = terrain.height(x, y, d) - 0.01
    rot = np.stack([nrng.normal(0, 0.1, k), nrng.normal(0, 0.1, k), nrng.uniform(0, 2 * np.pi, k)], axis=1)
    s = nrng.uniform(0.7, 1.3, k)
    scatter_object("Grass", np.column_stack([x, y, z]), rot, np.column_stack([s, s, s * nrng.uniform(0.8, 1.2, k)]),
                   nrng.integers(0, ng_, k), c_ground, coll, 0.5)

    # --- leaf litter --------------------------------------------------------------
    coll = make_collection("Assets litter", assets)
    nlit = 10
    for i in range(nlit):
        new_object(f"litter_{i:02d}", build_litter_leaf(rng, M["litter"], "oak" if i >= 7 else "beech"), coll)
    x, y, r = views.sample(nrng, 380 * opts.density, 0.3, 24.0, 0.28)
    d = path.distance(x, y)
    prob = (1.0 - 0.62 * smoothstep(6.0, 12.0, r)) * (1.0 - smoothstep(14.0, 24.0, r)) * (1.0 - 0.6 * path.mask(d))
    sel = nrng.random(len(x)) < prob
    x, y, d = x[sel], y[sel], d[sel]
    k = len(x)
    z = terrain.height(x, y, d) + nrng.uniform(0.0, 0.012, k)
    n = terrain.normal(x, y)
    R = frames_from_normals(n, nrng.uniform(0, 2 * np.pi, k)) @ tilt_matrices(nrng, k, 0.25)
    s = nrng.uniform(0.8, 1.25, k)
    scatter_object("Leaf_Litter", np.column_stack([x, y, z]), euler_xyz(R), np.repeat(s[:, None], 3, axis=1),
                   nrng.integers(0, nlit, k), c_ground, coll, 0.1)

    # --- fallen twigs -------------------------------------------------------------
    coll = make_collection("Assets twigs", assets)
    ntw = 8
    for i in range(ntw):
        new_object(f"twig_{i:02d}", build_twig(rng, M["deadwood"]), coll)
    x, y, r = views.sample(nrng, 0.6 * opts.density, 0.5, 25.0, 0.28)
    k = len(x)
    z = terrain.height(x, y) + 0.003
    n = terrain.normal(x, y)
    R = frames_from_normals(n, nrng.uniform(0, 2 * np.pi, k)) @ tilt_matrices(nrng, k, 0.05)
    s = nrng.uniform(0.7, 1.3, k)
    scatter_object("Twigs", np.column_stack([x, y, z]), euler_xyz(R), np.repeat(s[:, None], 3, axis=1),
                   nrng.integers(0, ntw, k), c_ground, coll, 0.5)

    # --- rocks ------------------------------------------------------------------
    coll = make_collection("Assets rocks", assets)
    nrk = 6
    for i in range(nrk):
        new_object(f"rock_{i:02d}", build_rock(rng, M["rock"], 1.0), coll)
    x, y, r = views.sample(nrng, None, 3.0, 45.0, 0.3, count=400)
    d = path.distance(x, y)
    keep = (d > 1.0) & (obstacles.clearance(x, y) > 0.8)
    x, y, d = x[keep][:22], y[keep][:22], d[keep][:22]
    k = len(x)
    sz = nrng.uniform(0.18, 0.75, k) * (1 + (nrng.random(k) < 0.2) * 0.8)
    z = terrain.height(x, y, d) - sz * 0.32
    rot = np.stack([nrng.normal(0, 0.15, k), nrng.normal(0, 0.15, k), nrng.uniform(0, 2 * np.pi, k)], axis=1)
    scatter_object("Rocks", np.column_stack([x, y, z]), rot, np.repeat(sz[:, None], 3, axis=1),
                   nrng.integers(0, nrk, k), c_props, coll)

    # --- light, sky, atmosphere -------------------------------------------------
    setup_world(scene, to_sun, LOOK["sky_strength"])
    setup_sun(c_env, to_sun)
    if not opts.no_fog:
        add_fog(c_env, ((cx - 300.0, cy - 40.0, -8.0), (cx + 300.0, cy + 400.0, 50.0)),
                LOOK["fog_density"], LOOK["fog_anisotropy"])
    setup_render(scene, opts)
    try:
        setup_compositor(scene)
    except Exception as exc:        # the finish is optional; never lose the scene over it
        log(f"compositor setup skipped: {exc!r}")

    # keep the asset library out of the render; the instancers still read it
    scene.view_layers[0].layer_collection.children[assets.name].exclude = True
    log("scene built")
    return scene


def build_log(terrain, mat, coll, rng, a, b, radius):
    n = 48
    t = np.linspace(0.0, 1.0, n)
    a, b = np.array(a), np.array(b)
    d = b - a
    side = np.array([-d[1], d[0]]) / np.linalg.norm(d)
    xy = a[None] + t[:, None] * d[None] + side[None] * (0.35 * np.sin(np.pi * t) + 0.08 * np.sin(5 * t))[:, None]
    rad = radius * (1.0 - 0.3 * t) * (1.0 + 0.04 * np.sin(17 * t))
    z = terrain.height(xy[:, 0], xy[:, 1]) + rad * 0.55
    pts = np.column_stack([xy, z])
    wav = [(k, rng.uniform(0.02, 0.06) / (1 + 0.15 * k), rng.uniform(0, 6.3), rng.uniform(-3, 3))
           for k in range(2, 12)]
    lump = [(rng.uniform(0, 1), rng.uniform(0, 6.3), rng.uniform(0.05, 0.15)) for _ in range(6)]

    def radial(th, P):
        s = np.linspace(0.0, 1.0, len(P))[:, None]
        out = np.ones((len(P), len(th)))
        for k, amp, ph, c in wav:
            out += amp * np.sin(k * th[None, :] + ph + c * s)
        for s0, a0, amp in lump:     # knots / bulges
            out += amp * np.exp(-((s - s0) / 0.03) ** 2) * np.exp(-(np.angle(np.exp(1j * (th[None, :] - a0))) / 0.5) ** 2)
        # the underside is squashed into the soil
        out *= 1.0 - 0.18 * np.clip(-np.sin(th[None, :]), 0.0, 1.0)
        return out
    mb = MeshBuilder()
    add_tube(mb, pts, rad, 36, 0, radial, cap=False)
    # jagged broken end caps
    for end in (0, -1):
        c = pts[end]
        tan = nrm(pts[1] - pts[0]) if end == 0 else nrm(pts[-1] - pts[-2])
        ring_start = 0 if end == 0 else (n - 1) * 36
        k = 36
        rim = np.arange(ring_start, ring_start + k)
        tip = c + tan * (0.12 if end == -1 else -0.12) * rng.uniform(0.5, 1.5)
        base = mb.add_verts(tip[None])
        jj = np.arange(k)
        if end == -1:
            tris = np.stack([rim, rim[(jj + 1) % k], np.full(k, base)], -1)
        else:
            tris = np.stack([rim[(jj + 1) % k], rim, np.full(k, base)], -1)
        mb.add_faces(tris, None, 0)
    # a few broken branch stubs
    br = Branch(pts, rad, 0)
    for _ in range(rng.randint(2, 4)):
        p, tan, r = br.sample(rng.uniform(0.2, 0.9))
        dd = child_direction(tan[0], rng.uniform(0.3, 2.8), math.radians(rng.uniform(50, 80)))
        s = grow(rng, p[0], dd, rng.uniform(0.2, 0.7), r[0] * 0.3, r[0] * 0.2, 0.08, 0.2, 0.0, 1)
        add_tube(mb, s.pts, s.rad, 10, 0, None, True, 5.0)
    me = mb.build("Fallen_Log", [mat])
    ob = new_object("Fallen_Log", me, coll)
    return ob, pts


