def side_rotation(side):
    """Rotation taking local X->world Y (length), local Y->world +/-Z, local Z->outward X."""
    if side > 0:
        m = Matrix(((0, 0, 1), (1, 0, 0), (0, 1, 0)))
    else:
        m = Matrix(((0, 0, -1), (1, 0, 0), (0, -1, 0)))
    return m.to_euler()


