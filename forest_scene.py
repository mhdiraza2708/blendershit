def build_fern(rng, detail, mat):
    mb = MeshBuilder()
    nr = np.random.default_rng(rng.randrange(1 << 30))
    nf = rng.randint(8, 14)
    size = rng.uniform(0.75, 1.35)
    rows_n = 12 if detail >= 1 else 7
    for f in range(nf):
        L = size * rng.uniform(0.75, 1.1)
        az = 2 * math.pi * f / nf + rng.gauss(0.0, 0.2)
        e0 = math.radians(rng.uniform(52.0, 78.0))
        droop = math.radians(rng.uniform(75.0, 125.0))
        m = 26
        t = np.linspace(0.0, 1.0, m)
        el = e0 - droop * t ** 1.7
        dirs = np.stack([np.cos(el) * math.cos(az), np.cos(el) * math.sin(az), np.sin(el)], axis=1)
        start = np.array([0.025 * math.cos(az), 0.025 * math.sin(az), 0.0])
        pts = np.vstack([start, start + np.cumsum(dirs[:-1] * (L / (m - 1)), axis=0)])
        rad = 0.0035 * (1.0 - 0.75 * t)
        frand = rng.random()
        V, Q, QUV, Tr, TUV, co = tube(pts, rad, 4, None, True)
        ring = np.repeat(np.arange(m - 1), 4)          # ring index of every rachis quad
        QUV = QUV.copy()
        QUV[:, 0:2, 1] = t[ring][:, None]
        QUV[:, 2:4, 1] = t[ring + 1][:, None]
        TUV = TUV.copy()
        TUV[..., 1] = 1.0
        base = mb.add_verts(V)
        mb.add_faces(Q + base, QUV, 0, {"frond_rand": ("FLOAT", frand)})
        mb.add_faces(Tr + base, TUV, 0, {"frond_rand": ("FLOAT", frand)})
        # pinnae
        br = Branch(pts, rad, 0)
        npin = int(rng.uniform(24, 32) * (1.0 if detail >= 1 else 0.75))
        tp = np.linspace(0.1, 0.985, npin)
        P, T, _ = br.sample(tp)
        S0 = nrm(np.cross(T, np.array([0.0, 0.0, 1.0])))
        Nf = nrm(np.cross(S0, T))
        tt = (tp - 0.1) / 0.885
        prof = (0.25 + tt) ** 0.6 * (1.0 - tt) ** 1.1
        lp = L * 0.2 * prof / prof.max() + 0.01
        rows = []
        for j in range(1, rows_n):
            u = j / rows_n
            w = 0.13 * (1.0 - u) ** 0.5 * (1.0 if j % 2 else 0.55)
            rows.append((u, w))
        tmpl = leaf_template(rows)
        for sgn in (1.0, -1.0):
            ang = np.radians(nr.uniform(58.0, 72.0, npin))
            D = nrm(S0 * sgn * np.sin(ang)[:, None] + T * np.cos(ang)[:, None] + Nf * 0.12)
            Np = nrm(Nf - (np.sum(Nf * D, axis=1))[:, None] * D)
            roll = nr.normal(0.0, 0.2, npin) - 0.25 * sgn
            Np = nrm(Np * np.cos(roll)[:, None] + np.cross(D, Np) * np.sin(roll)[:, None])
            V0, tris, uv = tmpl
            k = npin
            Wd = np.cross(Np, D)
            lx = V0[None, :, 0] * lp[:, None]
            ly = V0[None, :, 1] * lp[:, None]
            lz = (0.3 * np.abs(V0[None, :, 1]) - 0.12 * V0[None, :, 0] ** 2) * lp[:, None]
            verts = (P[:, None, :] + lx[..., None] * D[:, None, :] + ly[..., None] * Wd[:, None, :]
                     + lz[..., None] * Np[:, None, :])
            nv = len(V0)
            faces = (tris[None] + (np.arange(k) * nv)[:, None, None]).reshape(-1, 3)
            uvs = np.broadcast_to(uv[tris][None], (k,) + tris.shape + (2,)).copy()
            uvs[..., 1] = np.repeat(tp, tris.shape[0] * 3).reshape(k, tris.shape[0], 3)
            b2 = mb.add_verts(verts.reshape(-1, 3))
            mb.add_faces(faces + b2, uvs.reshape(-1, 3, 2), 0, {"frond_rand": ("FLOAT", frand)})
    return mb.build("fern", [mat])


def build_grass(rng, mat, n_blades, height):
    nr = np.random.default_rng(rng.randrange(1 << 30))
    k = n_blades
    r = 0.07 * np.sqrt(nr.random(k))
    a = nr.uniform(0, 2 * np.pi, k)
    base = np.stack([r * np.cos(a), r * np.sin(a), np.zeros(k)], axis=1)
    az = a + nr.normal(0, 0.6, k)
    el = np.radians(nr.uniform(58.0, 86.0, k))
    h = height * nr.uniform(0.5, 1.1, k)
    w = nr.uniform(0.0022, 0.0045, k)
    droop = nr.uniform(0.05, 0.45, k)
    t = np.linspace(0.0, 1.0, 6)
    dirh = np.stack([np.cos(az), np.sin(az), np.zeros(k)], axis=1)
    side = np.stack([-np.sin(az), np.cos(az), np.zeros(k)], axis=1)
    horiz = (h * np.cos(el))[:, None] * t[None, :] + (h * droop * 0.5)[:, None] * t[None, :] ** 2
    vert = (h * np.sin(el))[:, None] * t[None, :] - (h * droop)[:, None] * t[None, :] ** 2
    C = base[:, None, :] + horiz[..., None] * dirh[:, None, :] + vert[..., None] * np.array([0.0, 0.0, 1.0])
    wid = w[:, None] * (1.0 - t[None, :] ** 1.8)
    Lv = C + wid[..., None] * side[:, None, :]
    Rv = C - wid[..., None] * side[:, None, :]
    verts = np.concatenate([np.stack([Lv[:, :5], Rv[:, :5]], axis=2).reshape(k, 10, 3), C[:, 5:6]], axis=1)
    tris = []
    for i in range(4):
        l0, r0, l1, r1 = 2 * i, 2 * i + 1, 2 * i + 2, 2 * i + 3
        tris += [(l0, r0, r1), (l0, r1, l1)]
    tris.append((8, 9, 10))
    tris = np.array(tris)
    uvt = np.array([[0, t[i // 2]] if i % 2 == 0 else [1, t[i // 2]] for i in range(10)] + [[0.5, 1.0]])
    faces = (tris[None] + (np.arange(k) * 11)[:, None, None]).reshape(-1, 3)
    uvs = np.broadcast_to(uvt[tris][None], (k,) + tris.shape + (2,)).reshape(-1, 3, 2)
    mb = MeshBuilder()
    mb.add_verts(verts.reshape(-1, 3))
    mb.add_faces(faces, uvs, 0, {"blade_rand": ("FLOAT", np.repeat(nr.random(k), len(tris)))})
    return mb.build("grass", [mat])


def build_litter_leaf(rng, mat, shape):
    V0, tris, uv = leaf_template(LEAF_SHAPES[shape])
    s = rng.uniform(0.07, 0.1) if shape != "oak" else rng.uniform(0.08, 0.11)
    V = V0.copy()
    curl = rng.uniform(0.0, 0.9)
    bend = rng.uniform(-0.25, 0.35)
    twist = rng.uniform(-0.4, 0.4)
    wmax = np.abs(V[:, 1]).max()
    V[:, 2] = (curl * (V[:, 1] / wmax) ** 2 * wmax + bend * (V[:, 0] - 0.5) ** 2 + twist * (V[:, 0] - 0.5) * V[:, 1])
    off = rng.uniform(0.0, 100.0)
    V[:, 2] += np.array([mnoise.noise(Vector((x * 3.1 + off, y * 3.1, off))) * 0.05 for x, y, _ in V])
    V[:, 0] -= 0.5
    V *= s
    V[:, 2] -= V[:, 2].min() - 0.001
    mb = MeshBuilder()
    mb.add(V, tris, uv[tris], 0)
    return mb.build("litter", [mat])


def build_twig(rng, mat):
    mb = MeshBuilder()
    L = rng.uniform(0.25, 0.9)
    r0 = rng.uniform(0.004, 0.012)
    main = grow(rng, (-L / 2, 0.0, 0.0), (1.0, rng.uniform(-0.2, 0.2), 0.0), L, r0, r0 * 0.4, 0.06, 0.6, 0.0, 0)
    main.pts[:, 2] = 0.0
    branches = [main]
    for _ in range(rng.randint(0, 3)):
        t = rng.uniform(0.2, 0.8)
        p, tan, r = main.sample(t)
        d = child_direction(tan[0], rng.choice([math.pi / 2, -math.pi / 2]), math.radians(rng.uniform(25, 60)))
        d.z = 0.0
        b = grow(rng, p[0], d, L * rng.uniform(0.15, 0.4), r[0] * 0.6, r[0] * 0.25, 0.05, 0.5, 0.0, 1)
        b.pts[:, 2] = 0.0
        branches.append(b)
    for k, b in enumerate(branches):
        add_tube(mb, b.pts + np.array([0.0, 0.0, r0 * 0.8]), b.rad, 5, 0, None, True, k * 1.3)
    return mb.build("twig", [mat])


def build_rock(rng, mat, size):
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=4, radius=1.0)
    V = np.array([v.co[:] for v in bm.verts])
    faces = [[v.index for v in f.verts] for f in bm.faces]
    bm.free()
    seed = Vector((rng.uniform(-50, 50), rng.uniform(-50, 50), rng.uniform(-50, 50)))
    disp = np.array([mnoise.fractal(Vector(v) * 0.9 + seed, 0.7, 2.1, 6) for v in V])
    V = V * (1.0 + 0.32 * disp)[:, None]
    for _ in range(rng.randint(4, 7)):          # flat fracture planes -> angular boulder
        n = nrm(np.array([rng.gauss(0, 1), rng.gauss(0, 1), rng.gauss(0, 0.8)]))
        c = rng.uniform(0.45, 0.8)
        dist = V @ n
        over = dist > c
        V[over] -= ((dist[over] - c) * 0.92)[:, None] * n
    V *= np.array([size, size * rng.uniform(0.6, 0.95), size * rng.uniform(0.5, 0.8)])
    mb = MeshBuilder()
    mb.add(V, np.array(faces), None, 0)
    return mb.build("rock", [mat])


