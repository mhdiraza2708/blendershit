def place_leaves(mb, template, P, D, N, size, fold, bend, twist, mat, fattrs, width=None):
    """Instance a leaf template (as real geometry) at P, pointing along D with
    its face normal near N. All per-leaf arrays have length k."""
    V0, tris, uv = template
    k = len(P)
    if k == 0:
        return
    W = np.cross(N, D)
    lx = V0[None, :, 0] * size[:, None]
    wv = size if width is None else size * width
    ly = V0[None, :, 1] * wv[:, None]
    lz = (fold[:, None] * np.abs(V0[None, :, 1]) - bend[:, None] * V0[None, :, 0] ** 2
          + twist[:, None] * V0[None, :, 0] * V0[None, :, 1]) * size[:, None]
    verts = (P[:, None, :] + lx[..., None] * D[:, None, :] + ly[..., None] * W[:, None, :]
             + lz[..., None] * N[:, None, :])
    nv = len(V0)
    faces = (tris[None, :, :] + (np.arange(k) * nv)[:, None, None]).reshape(-1, 3)
    uvs = np.broadcast_to(uv[tris][None], (k,) + tris.shape + (2,)).reshape(-1, 3, 2)
    fa = {name: (kind, np.repeat(np.asarray(vals, dtype=np.float64), len(tris), axis=0))
          for name, (kind, vals) in fattrs.items()}
    base = mb.add_verts(verts.reshape(-1, 3))
    mb.add_faces(faces + base, uvs, mat, fa)


